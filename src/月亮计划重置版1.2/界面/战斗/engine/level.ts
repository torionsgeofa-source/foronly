/** 上帝视角战力评级: 只依据真实等级, 与公开身份/头衔无关。 */
export function 战力评级(等级: number): string {
  if (等级 <= 10) return '九阶';
  if (等级 <= 20) return '八阶';
  if (等级 <= 30) return '七阶';
  if (等级 <= 40) return '六阶';
  if (等级 <= 50) return '五阶';
  if (等级 <= 60) return '四阶';
  if (等级 <= 70) return '三阶';
  if (等级 <= 80) return '二阶';
  if (等级 <= 85) return '一阶';
  return '色彩';
}

/** 根据敌人等级粗略折算经验奖励 */
export function 经验奖励(敌人等级列表: number[]): number {
  return 敌人等级列表.reduce((和, 等级) => 和 + Math.max(1, Math.round(等级 * 2)), 0);
}

export interface 升级结果 {
  等级: number;
  经验: number;
  升级次数: number;
  战力评级: string;
}

/** 结算经验并自动升级 (不超过 90 级) */
export function 结算经验(等级: number, 当前经验: number, 获得经验: number): 升级结果 {
  let 新等级 = Math.max(1, Math.min(等级上限, 等级));
  let 经验 = Math.max(0, 当前经验) + Math.max(0, 获得经验);
  let 升级次数 = 0;
  while (新等级 < 等级上限 && 经验 >= 升级所需经验(新等级)) {
    经验 -= 升级所需经验(新等级);
    新等级 += 1;
    升级次数 += 1;
  }
  if (新等级 >= 等级上限) 经验 = 0;
  return { 等级: 新等级, 经验, 升级次数, 战力评级: 战力评级(新等级) };
}

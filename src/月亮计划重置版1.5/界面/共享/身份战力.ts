/** 计算生命上限 = 阶层初始生命 + 成长系数 × 等级 + 生命加成 */
export function 计算生命上限(阶层: string, 等级: number, 生命加成 = 0): number {
  const 条目 = 阶层表[(阶层 as 阶层名)] ?? 阶层表.普通;
  const 级 = Number.isFinite(等级) ? 等级 : 1;
  return Math.max(1, Math.round(条目.初始 + 条目.成长 * 级 + (生命加成 || 0)));
}

const 中文数字: Record<string, number> = { 一: 1, 二: 2, 三: 3, 四: 4, 五: 5, 六: 6, 七: 7, 八: 8, 九: 9 };
const 阶数到战力: Record<number, 战力层级名> = {
  1: '一阶', 2: '二阶', 3: '三阶', 4: '四阶', 5: '五阶', 6: '六阶', 7: '七阶', 8: '八阶', 9: '九阶',
};

/**
 * 由身份文本推断战力层级:
 * - 含「色彩」→ 色彩; 含「N阶」(中文/阿拉伯) → 对应阶数;
 * - 含 普通/平民/市民/路人/百姓/无名/杂鱼/杂兵/耗子 → 普通人;
 * - 其余视为 普通人 (可被剧情 / AI 显式覆盖)。
 */
export function 身份推战力层级(身份: string): 战力层级名 {
  const 文本 = String(身份 ?? '');
  if (/色彩/.test(文本)) return '色彩';
  const 匹配 = 文本.match(/([一二三四五六七八九]|[1-9])\s*阶/);
  if (匹配) {
    const 数 = 中文数字[匹配[1]] ?? Number(匹配[1]);
    if (阶数到战力[数]) return 阶数到战力[数];
  }
  return '普通人';
}

/** 由战力层级取一个代表等级 (区间中值, 取整) */
export function 由战力取等级(战力: 战力层级名): number {
  const [低, 高] = 战力到等级区间[战力] ?? 战力到等级区间.普通人;
  return Math.round((低 + 高) / 2);
}

/** 由身份一次性推导战力层级 / 生命层级 / 等级 */
export function 按身份推战力配置(身份: string): { 战力层级: 战力层级名; 阶层: 阶层名; 等级: number } {
  const 战力层级 = 身份推战力层级(身份);
  return { 战力层级, 阶层: 战力到阶层[战力层级], 等级: 由战力取等级(战力层级) };
}


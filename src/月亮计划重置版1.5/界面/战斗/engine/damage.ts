import type { 技能, 战斗单位, 追加伤害记录, 伤害明细, 技能效果, 效果上下文 } from './types';
import { 夹取 } from './rng';
import { 聚合加成, 施加技能附带状态, 执行效果, 读取, 满足条件 } from './status';

/** 单条抗性倍率对应的静态修正 */
export function 抗性修正(倍率: number): number {
  if (倍率 <= 0) return -0.5;
  if (倍率 >= 1) return 倍率 - 1;
  return (倍率 - 1) / 2;
}

export function 攻防等级修正(攻击等级: number, 防御等级: number): number {
  const 差 = 攻击等级 - 防御等级;
  return 差 / (Math.abs(差) + 25);
}

export function 混乱档位(单位: 战斗单位): number {
  if (!(单位.混乱阈值 > 0 && 单位.混乱值 >= 单位.混乱阈值)) return 0;
  return 单位.混乱值 >= 单位.混乱阈值 * 2 ? 2 : 1;
}

/**
 * 先扣护盾再扣生命: 护盾吸收 min(护盾, 伤害), 溢出部分作用于生命值。
 * 返回实际从生命值扣除的点数 (被护盾吸收的部分不计), 供混乱累积使用。
 */
export function 扣除护盾与生命(单位: 战斗单位, 伤害: number): number {
  let 剩余 = Math.max(0, 伤害);
  const 护盾 = 单位.护盾 ?? 0;
  if (护盾 > 0) {
    const 吸收 = Math.min(护盾, 剩余);
    单位.护盾 = 护盾 - 吸收;
    剩余 -= 吸收;
  }
  const 实际扣血 = Math.min(单位.生命值, 剩余);
  单位.生命值 = Math.max(0, 单位.生命值 - 剩余);
  return 实际扣血;
}

export function 应用追加伤害(单位: 战斗单位, 追加: 追加伤害记录[]): void {
  for (const 项 of 追加) {
    if (项.类型 === '理智') {
      单位.理智值 = 夹取(单位.理智值 - 项.数值, -45, 45);
    } else {
      扣除护盾与生命(单位, 项.数值);
    }
  }
}

export interface 伤害输入 {
  攻击方: 战斗单位;
  受击方: 战斗单位;
  技能: 技能;
  硬币威力: number;
  拼点回合数: number;
  暴击: boolean;
  追加: 追加伤害记录[];
  /** 该枚硬币自身的命中效果; 有值时优先于技能级 effects / 字符串效果 */
  命中效果?: 技能效果[];
  /** 效果落点解析所需的战斗上下文 (缺省时仅 自己 / 敌人 落点生效) */
  上下文?: 效果上下文;
}

export function 计算伤害(输入: 伤害输入): 伤害明细 {
  const { 攻击方, 受击方, 技能 } = 输入;
  const 聚合 = 聚合加成(攻击方);
  const 受击加成 = 聚合加成(受击方);

  const 罪孽修正 = 抗性修正(受击方.罪孽抗性[技能.罪孽] ?? 1);
  const 物理修正 = (() => {
    const 档位 = 混乱档位(受击方);
    if (档位 > 0) return 档位 * 0.5 + 0.5;
    return 抗性修正(受击方.物理抗性[技能.攻击类型] ?? 1);
  })();

  const 攻击等级 = 攻击方.攻击等级 + 聚合.攻击等级 + (技能.攻击等级修正 ?? 0);
  const 防御等级 = 受击方.防御等级 + 受击加成.防御等级;
  const 等级修正 = 攻防等级修正(攻击等级, 防御等级);
  const 暴击修正 = 输入.暴击 ? 0.2 + 聚合.暴击伤害 : 0;
  const 拼点修正 = 输入.拼点回合数 * 0.03;

  const 静态 = 罪孽修正 + 物理修正 + 等级修正 + 暴击修正 + 拼点修正;

  // 增伤乘区 (进攻方): 伤害强化 − 伤害弱化 + 满足条件的 条件增伤
  // 条件增伤以**受击方**判定条件是否成立 (与规则文本一致)
  let 条件增伤和 = 0;
  const 效果列表: 技能效果[] = [...(技能.effects ?? []), ...(输入.命中效果 ?? [])];
  for (const 效果 of 效果列表) {
    if (效果.type === '条件增伤' && 满足条件(受击方, 效果.条件)) 条件增伤和 += 效果.数值 / 100;
  }
  const 增伤 = 夹取((读取(攻击方, '伤害强化') - 读取(攻击方, '伤害弱化')) * 0.1 + 条件增伤和, -1, 2);
  // 减伤乘区 (受击方): 守护 + 忍耐 − 易损, 正值=减伤, 负值=增伤
  const 减伤 = 夹取((读取(受击方, '守护') + 读取(受击方, '忍耐') - 读取(受击方, '易损')) * 0.1, -1, 1);

  const 硬币威力 = 输入.硬币威力;
  let 数值 = Math.floor(硬币威力 * (1 + 静态) * (1 + 增伤) * (1 - 减伤));
  数值 = Math.max(1, 数值);
  数值 = Math.max(数值, Math.floor(Math.max(0, 硬币威力) * 0.05));

  return {
    目标: 受击方.名称,
    数值,
    暴击: 输入.暴击,
    罪孽: 技能.罪孽,
    攻击类型: 技能.攻击类型,
    静态,
    增伤,
    减伤,
    追加: [...输入.追加],
  };
}

/** 将伤害与追加伤害应用到受击方 */
export function 执行命中(输入: 伤害输入): 伤害明细 {
  const 明细 = 计算伤害(输入);
  // 混乱值仅按实际损失的生命值累积, 被护盾吸收的伤害不计
  const 实际扣血 = 扣除护盾与生命(输入.受击方, 明细.数值);
  输入.受击方.混乱值 += 实际扣血;
  应用追加伤害(输入.受击方, 输入.追加);
  // 命中效果结算优先级: 硬币自身的结构化命中效果 > 技能级 effects / 文本效果兜底。
  // 仅当该技能的所有硬币都没有结构化「命中效果」时, 才允许技能级兜底, 避免与逐币效果重复结算。
  if (输入.命中效果 && 输入.命中效果.length > 0) {
    执行效果(输入.攻击方, 输入.受击方, 输入.命中效果, 输入.上下文);
  } else if (!技能含硬币命中效果(输入.技能)) {
    施加技能附带状态(输入.攻击方, 输入.受击方, 输入.技能, 输入.上下文);
  }
  return 明细;
}

/** 该技能是否有任一硬币携带结构化命中效果 (有则技能级文本 / effects 不再兜底) */
function 技能含硬币命中效果(技能: 技能): boolean {
  return (技能.硬币 ?? []).some(硬币 => (硬币.命中效果?.length ?? 0) > 0);
}

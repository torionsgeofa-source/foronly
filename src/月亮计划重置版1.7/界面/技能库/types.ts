/** 依据模板与用户输入, 创建一份可编辑的技能草稿 (深拷贝, 并补齐可编辑数组) */
export function 建草稿(定义?: 技能定义): 技能定义 {
  if (!定义) {
    return { 名称: '', 类别: '战斗', 罪孽: '暴怒', 攻击类型: '打击', 硬币: [], 攻击等级修正: 0, 攻击容量: 1, 效果: '', 描述: '', effects: [] };
  }
  const 草稿 = klona(定义);
  草稿.硬币 = 规范化硬币(草稿).map(项 => ({ ...项, 命中效果: (项.命中效果 ?? []).map(效果 => ({ ...效果 })) }));
  草稿.effects = (草稿.effects ?? []).map(效果 => ({ ...效果 }));
  return 草稿;
}

/** 将 硬币 派生字段与现有 硬币威力 / 硬币类型 数组同步 */
export function 规范化硬币(定义: 技能定义): 战斗技能硬币[] {
  const 补齐 = (项: 战斗技能硬币, 下标: number): 战斗技能硬币 => ({
    威力: 项.威力 ?? 定义.硬币威力?.[下标] ?? 0,
    类型: 项.类型 ?? 定义.硬币类型?.[下标] ?? '普通',
    命中效果: 项.命中效果 ?? [],
  });
  if (Array.isArray(定义.硬币) && 定义.硬币.length) return 定义.硬币.map(补齐);
  const 威力表 = 定义.硬币威力 ?? [];
  const 类型表 = 定义.硬币类型 ?? [];
  return 威力表.map((威力, 下标) => ({ 威力, 类型: 类型表[下标] ?? '普通', 命中效果: [] }));
}

import type { 技能, 硬币, 战斗单位, 拼点结果, 拼点回合记录, 拼点硬币记录 } from './types';
import { 可拼点守备列表 } from './types';
import { 正面率, 掷硬币, 默认随机源, type 随机源 } from './rng';
import { 聚合加成, 掷币触发, 调整SP } from './status';
import { 扣除护盾与生命 } from './damage';

const 最大拼点次数 = 99;

export function 构建硬币(技能: 技能): 硬币[] {
  return 技能.硬币威力.map((威力, 下标) => ({
    id: 下标 + 1,
    威力,
    类型: 技能.硬币类型[下标] ?? '普通',
    正面: false,
    已摧毁: false,
    已破碎: false,
  }));
}

/** 存活硬币: 尚未被摧毁 (含「已输过」的硬币, 它们仍参与掷点与攻击) */
function 存活硬币(硬币: 硬币[]): 硬币[] {
  return 硬币.filter(硬币 => !硬币.已摧毁);
}

/** 健在硬币: 尚未被摧毁、也尚未「输过」(已破碎) 的硬币。一方没有健在硬币即判定拼点结束。 */
function 健在硬币(硬币: 硬币[]): 硬币[] {
  return 硬币.filter(硬币 => !硬币.已摧毁 && !硬币.已破碎);
}

function 有截除(硬币: 硬币[]): boolean {
  return 健在硬币(硬币).some(硬币 => 硬币.类型 === '截除');
}

function 有无我(硬币: 硬币[]): boolean {
  return 健在硬币(硬币).some(硬币 => 硬币.类型 === '无我');
}

interface 掷币结果 {
  记录: 拼点硬币记录[];
  威力: number;
}

function 一侧掷币(
  硬币列表: 硬币[],
  技能: 技能,
  单位: 战斗单位,
  拼点加成: number,
  攻击等级加成: number,
  麻痹: number,
  rng: 随机源,
): 掷币结果 {
  const 概率 = 正面率(单位.理智值);
  const 记录: 拼点硬币记录[] = [];
  let 合计 = 技能.基础威力 + 拼点加成 + 攻击等级加成;

  for (const 硬币 of 存活硬币(硬币列表)) {
    if (硬币.已破碎) {
      硬币.正面 = false;
      记录.push({ id: 硬币.id, 威力: 硬币.威力, 类型: 硬币.类型, 正面: false, 固定: true });
      合计 += 1;
      continue;
    }
    const 正面 = 掷硬币(概率, rng);
    硬币.正面 = 正面;
    const 威力 = 硬币.id <= 麻痹 ? 0 : 硬币.威力;
    记录.push({ id: 硬币.id, 威力, 类型: 硬币.类型, 正面, 固定: false });
    if (正面) 合计 += 威力;
  }

  return { 记录, 威力: 合计 };
}

/** 可拼点守备(闪避/防御/强化防御)在拼点时使用防御等级, 其余(攻击/反击)使用攻击等级 */
export function 是守备可拼点(技能: 技能 | undefined): boolean {
  return !!技能 && !!技能.守备类型 && 可拼点守备列表.includes(技能.守备类型);
}

export function 拼点等级(单位: 战斗单位, 技能: 技能): number {
  const 加成 = 聚合加成(单位);
  if (是守备可拼点(技能)) return 单位.防御等级 + 加成.防御等级;
  return 单位.攻击等级 + 加成.攻击等级 + (技能.攻击等级修正 ?? 0);
}

/**
 * 拼点加成: 默认只有等级更高的一方获得 +floor(差/3);
 * 但攻击 vs 可拼点守备时, 只把加成给守备方 (反击按攻击 vs 攻击处理)。
 */
function 计算拼点加成(左侧技能: 技能, 右侧技能: 技能, 左等级: number, 右等级: number): [number, number] {
  const 左守 = 是守备可拼点(左侧技能);
  const 右守 = 是守备可拼点(右侧技能);
  if (左守 !== 右守) {
    if (左守) return [Math.max(0, Math.floor((左等级 - 右等级) / 3)), 0];
    return [0, Math.max(0, Math.floor((右等级 - 左等级) / 3))];
  }
  const 差 = 左等级 - 右等级;
  if (差 > 0) return [Math.floor(差 / 3), 0];
  if (差 < 0) return [0, Math.floor(-差 / 3)];
  return [0, 0];
}

/** 同一拼点序列中第 N 次胜利的 SP 收益: 10, 12, 14, 17 ... */
function 胜利SP收益(次数: number): number {
  return Math.floor(10 * Math.pow(1.2, Math.max(0, 次数 - 1)));
}

interface 摧毁结果 {
  硬币id: number;
  类型: '摧毁' | '破碎' | '无';
}

/**
 * 取「最外面」的一枚健在硬币: 即序号(id)最大的一枚。硬币数组按 id 升序,
 * 因此从末尾往前找第一枚满足条件的。
 */
function 取最外健在(硬币列表: 硬币[], 谓词: (硬币: 硬币) => boolean = () => true): 硬币 | undefined {
  for (let i = 硬币列表.length - 1; i >= 0; i--) {
    const 硬币 = 硬币列表[i];
    if (!硬币.已摧毁 && !硬币.已破碎 && 谓词(硬币)) return 硬币;
  }
  return undefined;
}

/**
 * 拼点失败时消耗「最外面的一枚健在硬币」(序号最大的一枚):
 * 普通硬币被摧毁移除; 不可摧毁(红)/截除/无我硬币转为「已输过」(威力固定 1) 并保留。
 * 当一方再无健在硬币时, 拼点结束。
 */
function 消耗硬币(硬币列表: 硬币[]): 摧毁结果 {
  const 目标 = 取最外健在(硬币列表);
  if (!目标) return { 硬币id: -1, 类型: '无' };
  if (目标.类型 === '普通') {
    目标.已摧毁 = true;
    return { 硬币id: 目标.id, 类型: '摧毁' };
  }
  目标.已破碎 = true;
  return { 硬币id: 目标.id, 类型: '破碎' };
}

/** 截除: 额外直接摧毁对方最外面的一枚不可摧毁硬币 */
function 摧毁红币(硬币列表: 硬币[]): 摧毁结果 {
  const 红 = 取最外健在(硬币列表, 硬币 => 硬币.类型 !== '普通');
  if (红) {
    红.已摧毁 = true;
    return { 硬币id: 红.id, 类型: '摧毁' };
  }
  return { 硬币id: -1, 类型: '无' };
}

/** 无我: 额外直接摧毁对方最外面的一枚硬币 (优先普通) */
function 摧毁任意(硬币列表: 硬币[]): 摧毁结果 {
  const 目标 = 取最外健在(硬币列表, 硬币 => 硬币.类型 === '普通') ?? 取最外健在(硬币列表);
  if (目标) {
    目标.已摧毁 = true;
    return { 硬币id: 目标.id, 类型: '摧毁' };
  }
  return { 硬币id: -1, 类型: '无' };
}

function 快照(硬币列表: 硬币[]): 硬币[] {
  return 硬币列表.map(硬币 => ({ ...硬币 }));
}

/** 双方拼点, 返回完整过程与残余硬币 (残余硬币用于后续攻击) */
export function 拼点(左侧: 战斗单位, 左侧技能: 技能, 右侧: 战斗单位, 右侧技能: 技能, rng: 随机源 = 默认随机源): 拼点结果 {
  const 左硬币 = 构建硬币(左侧技能);
  const 右硬币 = 构建硬币(右侧技能);
  const 左侧初始硬币 = 快照(左硬币);
  const 右侧初始硬币 = 快照(右硬币);

  const 左加成 = 聚合加成(左侧);
  const 右加成 = 聚合加成(右侧);
  const 左等级 = 拼点等级(左侧, 左侧技能);
  const 右等级 = 拼点等级(右侧, 右侧技能);
  const [左攻级加成, 右攻级加成] = 计算拼点加成(左侧技能, 右侧技能, 左等级, 右等级);

  const 记录: 拼点回合记录[] = [];
  let 胜者: '左' | '右' | '无' = '无';

  for (let 回合数 = 1; 回合数 <= 最大拼点次数; 回合数++) {
    // 结束条件: 任一方没有任何「健在硬币」(未摧毁且未输过)
    const 左活 = 健在硬币(左硬币).length > 0;
    const 右活 = 健在硬币(右硬币).length > 0;
    if (!左活 || !右活) break;

    if (回合数 === 1) {
      // 流血等固定伤害与主伤害一致: 先扣护盾再扣生命
      for (const 项 of 掷币触发(左侧)) if (项.类型 === '固定') 扣除护盾与生命(左侧, 项.数值);
      for (const 项 of 掷币触发(右侧)) if (项.类型 === '固定') 扣除护盾与生命(右侧, 项.数值);
      if (左侧.生命值 <= 0 || 右侧.生命值 <= 0) break;
    }

    const 左掷 = 一侧掷币(左硬币, 左侧技能, 左侧, 左加成.拼点威力, 左攻级加成, 左加成.麻痹, rng);
    const 右掷 = 一侧掷币(右硬币, 右侧技能, 右侧, 右加成.拼点威力, 右攻级加成, 右加成.麻痹, rng);

    let 结果: '左胜' | '右胜' | '平局' = '平局';
    let 摧毁: { 方: '左' | '右'; 硬币id: number; 类型: '摧毁' | '破碎' } | null = null;
    let 额外击碎: { 方: '左' | '右'; 硬币id: number; 类型: '摧毁' | '破碎' } | null = null;

    if (左掷.威力 > 右掷.威力) {
      结果 = '左胜';
      胜者 = '左';
      const 摧毁结果 = 消耗硬币(右硬币);
      if (摧毁结果.硬币id > 0) 摧毁 = { 方: '右', 硬币id: 摧毁结果.硬币id, 类型: 摧毁结果.类型 === '破碎' ? '破碎' : '摧毁' };
      if (有截除(左硬币)) {
        const 额外 = 摧毁红币(右硬币);
        if (额外.硬币id > 0) 额外击碎 = { 方: '右', 硬币id: 额外.硬币id, 类型: '摧毁' };
      } else if (有无我(左硬币)) {
        const 额外 = 摧毁任意(右硬币);
        if (额外.硬币id > 0) 额外击碎 = { 方: '右', 硬币id: 额外.硬币id, 类型: '摧毁' };
      }
    } else if (右掷.威力 > 左掷.威力) {
      结果 = '右胜';
      胜者 = '右';
      const 摧毁结果 = 消耗硬币(左硬币);
      if (摧毁结果.硬币id > 0) 摧毁 = { 方: '左', 硬币id: 摧毁结果.硬币id, 类型: 摧毁结果.类型 === '破碎' ? '破碎' : '摧毁' };
      if (有截除(右硬币)) {
        const 额外 = 摧毁红币(左硬币);
        if (额外.硬币id > 0) 额外击碎 = { 方: '左', 硬币id: 额外.硬币id, 类型: '摧毁' };
      } else if (有无我(右硬币)) {
        const 额外 = 摧毁任意(左硬币);
        if (额外.硬币id > 0) 额外击碎 = { 方: '左', 硬币id: 额外.硬币id, 类型: '摧毁' };
      }
    }

    记录.push({
      回合数,
      左侧威力: 左掷.威力,
      右侧威力: 右掷.威力,
      左侧硬币: 左掷.记录,
      右侧硬币: 右掷.记录,
      结果,
      摧毁,
      额外击碎,
    });
  }

  const 左健 = 健在硬币(左硬币);
  const 右健 = 健在硬币(右硬币);
  if (左健.length > 0 && 右健.length === 0) 胜者 = '左';
  else if (右健.length > 0 && 左健.length === 0) 胜者 = '右';
  else if (左健.length > 0 && 右健.length > 0) {
    const 末 = 记录[记录.length - 1];
    胜者 = 末 ? (末.结果 === '左胜' ? '左' : 末.结果 === '右胜' ? '右' : '无') : '无';
  }

  // 拼点序列 SP: 每次胜利按 10 * 1.2^(n-1) 递增, 取整
  let 左胜次数 = 0;
  let 右胜次数 = 0;
  for (const 记录项 of 记录) {
    if (记录项.结果 === '左胜') 左胜次数 += 1;
    else if (记录项.结果 === '右胜') 右胜次数 += 1;
  }
  let 左SP = 0;
  let 右SP = 0;
  for (let i = 1; i <= 左胜次数; i++) 左SP += 胜利SP收益(i);
  for (let i = 1; i <= 右胜次数; i++) 右SP += 胜利SP收益(i);
  const 左实际SP = 左SP !== 0 ? 调整SP(左侧, 左SP) : 0;
  const 右实际SP = 右SP !== 0 ? 调整SP(右侧, 右SP) : 0;

  return {
    左侧名称: 左侧.名称,
    右侧名称: 右侧.名称,
    左侧技能: 左侧技能.名称,
    右侧技能: 右侧技能.名称,
    胜者,
    记录,
    左侧初始硬币,
    右侧初始硬币,
    左侧剩余硬币: 快照(左硬币),
    右侧剩余硬币: 快照(右硬币),
    左侧攻击等级加成: 左攻级加成,
    右侧攻击等级加成: 右攻级加成,
    左侧拼点威力加成: 左加成.拼点威力,
    右侧拼点威力加成: 右加成.拼点威力,
    左侧SP变化: 左实际SP,
    右侧SP变化: 右实际SP,
  };
}

/** 从拼点结果中取出某一方未被摧毁的硬币 (含「已输过」、威力固定 1 的硬币) 用于发动攻击 */
export function 可攻击硬币(硬币列表: 硬币[]): 硬币[] {
  return 硬币列表.filter(硬币 => !硬币.已摧毁);
}

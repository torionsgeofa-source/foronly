import { 规范化技能定义 } from './技能常量';
import { 规范化硬币 } from '../技能库/types';
import type { 技能定义, 技能效果, 技能类别, 战斗技能硬币 } from './技能常量';

/**
 * 共享技能编辑模型: 开局表单 与 技能库 两处使用同一结构, 保证字段 / 校验 / 规范化完全一致。
 * 数值字段用 number, 枚举用 string (允许 '无' 等表单占位), 硬币逐枚携带结构化命中效果。
 */
export interface 技能编辑 {
  名称: string;
  类别: string;
  描述: string;
  罪孽: string;
  攻击类型: string;
  守备类型: string;
  时机: string;
  条件: string;
  每回合一次: boolean;
  攻击等级修正: number;
  攻击容量: number;
  SP消耗: number;
  /** 拼点技能的基础威力 (拼点初始值)。必填: 填 0 即为基础威力 0 (不再留空派生) */
  基础威力: number;
  硬币: 战斗技能硬币编辑[];
  /** 被动 / 支援的结构化效果 (拼点技能不使用) */
  效果: 技能效果[];
}

export interface 战斗技能硬币编辑 {
  威力: number;
  类型: string;
  命中效果: 技能效果[];
}

/** 空技能草稿 (默认战斗类, 暴怒 / 打击 / 1 容量, 无硬币) */
export function 空技能编辑(): 技能编辑 {
  return {
    名称: '',
    类别: '战斗',
    描述: '',
    罪孽: '暴怒',
    攻击类型: '打击',
    守备类型: '',
    时机: '',
    条件: '',
    每回合一次: false,
    攻击等级修正: 0,
    攻击容量: 1,
    SP消耗: 0,
    基础威力: 0,
    硬币: [],
    效果: [],
  };
}

function 复制效果(效果: 技能效果): 技能效果 {
  return { ...效果 };
}

function 复制硬币(硬币: 战斗技能硬币): 战斗技能硬币编辑 {
  return {
    威力: 硬币.威力,
    类型: 硬币.类型,
    命中效果: (硬币.命中效果 ?? []).map(复制效果),
  };
}

/** 由技能定义 (库中权威定义) 构造可编辑草稿 (深拷贝) */
export function 从技能定义(定义: 技能定义): 技能编辑 {
  const 草稿 = 空技能编辑();
  return {
    ...草稿,
    名称: 定义.名称,
    类别: 定义.类别,
    描述: 定义.描述 ?? '',
    罪孽: 定义.罪孽 ?? '无',
    攻击类型: 定义.攻击类型 ?? '打击',
    守备类型: 定义.守备类型 ?? '',
    时机: 定义.时机 ?? '',
    条件: 定义.条件 ?? '',
    每回合一次: 定义.每回合一次 ?? false,
    攻击等级修正: 定义.攻击等级修正 ?? 0,
    攻击容量: 定义.攻击容量 ?? 1,
    SP消耗: 定义.SP消耗 ?? (定义.类别 === 'EGO' ? 10 : 0),
    基础威力: 定义.基础威力 ?? 0,
    硬币: 规范化硬币(定义).map(复制硬币),
    效果: (定义.effects ?? []).map(复制效果),
  };
}

/**
 * 将编辑模型收敛为技能定义。
 * 若传入 `原定义`, 则以其为基础合并 (非法 / 缺失字段优先保留原值);
 * 枚举合法化、数值夹取、按类别清理字段、被动/支援目标过滤与补展示文本
 * 统一委托给 `界面/共享/技能常量.ts` 的 `规范化技能定义`。
 */
export function 到技能定义(编辑: 技能编辑, 原定义?: 技能定义): 技能定义 {
  const 是被动支援 = 编辑.类别 === '被动' || 编辑.类别 === '支援';
  const 原始: Partial<技能定义> = {
    名称: 编辑.名称,
    类别: 编辑.类别 as 技能类别,
    描述: 编辑.描述,
    效果: 原定义?.效果,
  };
  if (是被动支援) {
    原始.时机 = 编辑.时机 as 技能定义['时机'];
    原始.条件 = 编辑.条件 || undefined;
    原始.每回合一次 = 编辑.每回合一次 || undefined;
    原始.effects = 编辑.效果.map(复制效果);
  } else {
    原始.罪孽 = 编辑.罪孽 as 技能定义['罪孽'];
    原始.攻击类型 = 编辑.攻击类型 as 技能定义['攻击类型'];
    原始.守备类型 = 编辑.守备类型 as 技能定义['守备类型'];
    原始.攻击等级修正 = 编辑.攻击等级修正;
    原始.攻击容量 = 编辑.攻击容量;
    原始.SP消耗 = 编辑.类别 === 'EGO' ? 编辑.SP消耗 : 0;
    原始.基础威力 = 编辑.基础威力;
    原始.硬币 = 编辑.硬币.map(项 => ({ 威力: 项.威力, 类型: 项.类型 as 战斗技能硬币['类型'], 命中效果: (项.命中效果 ?? []).map(复制效果) }));
  }
  return 规范化技能定义(原始, 原定义);
}

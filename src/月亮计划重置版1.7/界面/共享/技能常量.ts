  硬币威力?: number[];
  硬币类型?: 硬币类型[];
  硬币?: 战斗技能硬币[];
  攻击等级修正?: number;
  攻击容量?: number;
  /** 展示文本 (派生): 由 硬币[].命中效果 / effects 自动生成, 不手写 */

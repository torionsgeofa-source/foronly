export interface 生成技能集 {
  技能: 技能定义[];
  技能名: string[];
}

/**
 * 按身份 + 阶层生成一整套规范化技能 (N 战斗 + 1 守备 + 1 支援 + 1 被动)。
 * 生成对同一 (身份, 阶层) 确定; 名称在返回集合内唯一。
 */
export function 按身份阶层生成技能(身份: string, 阶层: 阶层名, 等级: number): 生成技能集 {
  const 主题 = 选主题(身份);
  const 层数 = 阶层层数规格[阶层];
  const 含红币 = 可含红币[阶层];
  const 已用 = new Set<string>();
  const 技能: 技能定义[] = [];
  const 点数表 = 战斗技能点数规格[阶层] ?? 战斗技能点数规格.普通;
  const 硬币表 = 战斗硬币数规格[阶层] ?? 战斗硬币数规格.普通;
  void 等级;

  点数表.forEach((点数, i) => {
    const 种子 = 散列(`${身份}|${阶层}|战技|${i}`);
    const 名称 = 取唯一名(主题.技能名池, 已用, `${主题.主题名}战技`, i);
    const 硬币数 = 硬币表[i % 硬币表.length];
    const { 基础威力, 硬币 } = 造硬币(点数, 硬币数, 含红币, 种子);
    const 状态 = 合法状态名(取子项(主题.攻击状态, 种子), '破裂');
    const 硬币定义 = 硬币.map((c, idx) => ({
      威力: c.威力,
      类型: c.类型,
      命中效果: idx === 硬币.length - 1
        ? [{ type: '施加状态', 目标: '敌人', 状态, 层数, 强度: 0 } as 技能效果]
        : [],
    }));
    技能.push(
      规范化技能定义({
        名称,
        类别: '战斗',
        罪孽: 取子项(主题.罪孽, 种子),
        攻击类型: 取子项(主题.攻击, 种子 >> 3),
        基础威力,
        硬币: 硬币定义,
        攻击等级修正: 0,
        攻击容量: 1,
        描述: `AI原创NPC技能：${主题.主题名}系·${阶层}战斗技能。`,
      }),
    );
  });

  // 守备
  {
    const 种子 = 散列(`${身份}|${阶层}|守备`);
    const 名称 = 取唯一名([], 已用, `${主题.主题名}守备`, 0);
    const 点数 = 守备点数规格[阶层] ?? 10;
    const 基础威力 = Math.max(3, Math.round(点数 * 0.5));
    const 守备类型 = 取子项<守备类型名>(['防御', '闪避', '强化防御', '反击'], 种子);
    技能.push(
      规范化技能定义({
        名称,
        类别: '守备',
        守备类型,
        罪孽: 取子项(主题.罪孽, 种子),
        攻击类型: 取子项(主题.攻击, 种子 >> 3),
        基础威力,
        硬币: [{ 威力: Math.max(1, 点数 - 基础威力), 类型: '普通', 命中效果: [] }],
        攻击等级修正: 0,
        攻击容量: 1,
        描述: `AI原创NPC技能：${主题.主题名}系·${阶层}守备技能。`,
      }),
    );
  }

  // 支援 (战斗开始时, 全体友方)
  {
    const 种子 = 散列(`${身份}|${阶层}|支援`);
    const 名称 = 取唯一名([], 已用, `${主题.主题名}支援`, 0);
    const 状态 = 合法状态名(取子项(主题.我方状态, 种子), '强壮');
    技能.push(
      规范化技能定义({
        名称,
        类别: '支援',
        时机: '战斗开始时',
        effects: [{ type: '施加状态', 目标: '全体盟友', 状态, 层数, 强度: 0 }],
        描述: `AI原创NPC技能：${主题.主题名}系·${阶层}支援。`,
      }),
    );
  }

  // 被动 (自我增益)
  {
    const 种子 = 散列(`${身份}|${阶层}|被动`);
    const 名称 = 取唯一名([], 已用, `${主题.主题名}被动`, 0);
    const 状态 = 合法状态名(取子项(主题.自我状态, 种子), '强壮');
    const 时机 = 取子项(['回合开始时', '受击时', '命中时'], 种子) as 技能定义['时机'];
    技能.push(
      规范化技能定义({
        名称,
        类别: '被动',
        时机,
        每回合一次: 时机 === '回合开始时' ? undefined : true,
        effects: [{ type: '施加状态', 目标: '自己', 状态, 层数, 强度: 0 }],
        描述: `AI原创NPC技能：${主题.主题名}系·${阶层}被动。`,
      }),
    );
  }

  return { 技能, 技能名: 技能.map(s => s.名称) };
}

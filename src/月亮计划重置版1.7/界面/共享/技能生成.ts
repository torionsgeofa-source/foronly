function 散列(文本: string): number {
  let h = 2166136261;
  for (let i = 0; i < 文本.length; i++) {
    h ^= 文本.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

function 取子项<T>(数组: readonly T[], 种子: number): T {
  return 数组[Math.abs(种子) % 数组.length];
}

const 名称后缀池 = ['斩', '刺', '突', '坠', '击', '裂', '绞', '噬', '葬', '缚', '鸣', '啸', '涌', '铡', '贯'];

function 取名(候选: string[], 意象: string[], 种子: number, 已用: Set<string>, 兜底: string): string {
  const 可用 = 候选.filter(名 => 名 && !已用.has(名));
  let 名 = 可用.length > 0 ? 可用[0] : `${取子项(意象, 种子)}${取子项(名称后缀池, 种子 >> 3)}`;
  if (!名) 名 = 兜底;
  let n = 2;
  while (已用.has(名)) 名 = `${名}${n++}`;
  已用.add(名);
  return 名;
}

function 造硬币(点数: number, 硬币数: number, 含红币: boolean, 种子: number): { 基础威力: number; 硬币: { 威力: number; 类型: 硬币类型 }[] } {
  const 基础威力 = Math.max(3, Math.round(点数 * 0.4));
  const 硬币和 = Math.max(硬币数, 点数 - 基础威力);
  const 每枚 = Math.floor(硬币和 / 硬币数);
  const 余 = 硬币和 - 每枚 * 硬币数;
  const 硬币: { 威力: number; 类型: 硬币类型 }[] = [];
  for (let i = 0; i < 硬币数; i++) {
    const 红 = 含红币 && (i === 0 || (硬币数 >= 4 && i === 1));
    硬币.push({ 威力: 每枚 + (i < 余 ? 1 : 0), 类型: 红 ? '不可摧毁' : '普通' });
  }
  if (硬币数 >= 2 && 种子 % 2 === 1 && 硬币[0].威力 > 1) {
    硬币[0].威力 -= 1;
    硬币[1].威力 += 1;
  }
  return { 基础威力, 硬币 };
}


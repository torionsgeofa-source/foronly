export function 解析技能关键词(文本: string | undefined): 技能关键词 {
  const 结果: 技能关键词 = { 主题: [], 性格: [], 罪孽: [], 技能名: [] };
  if (!文本 || !文本.trim()) return 结果;
  for (const 段 of 文本.split(/[;；\n]+/)) {
    const 配对 = 段.split(/[=:：]/);
    if (配对.length < 2) continue;
    const 键 = 配对[0].trim();
    const 值 = 配对.slice(1).join('=').split(/[,，、/\s]+/).map(项 => 项.trim()).filter(Boolean);
    if (/主题|意象|风格|标签/i.test(键)) 结果.主题.push(...值);
    else if (/性格|气质/i.test(键)) 结果.性格.push(...值);
    else if (/罪孽/i.test(键)) {
      for (const 项 of 值) {
        const 罪孽 = 罪孽别名[项] ?? (罪孽列表.includes(项 as 罪孽名) ? (项 as 罪孽名) : undefined);
        if (罪孽) 结果.罪孽.push(罪孽);
      }
    } else if (/技能名|技能|名称/i.test(键)) 结果.技能名.push(...值);
  }
  return 结果;
}


/** 施加状态: DoT 写 强度+层数; 资源类只写 层数; 其余写 层数 + 持续回合 (永久仅高阶) */
function 状态效果(目标: 效果目标, 状态: string, 阶层: 阶层名, 永久 = false): 技能效果 {
  if (强度DoT状态.has(状态)) {
    return { type: '施加状态', 目标, 状态, 强度: DoT强度规格[阶层], 层数: 层数规格[阶层] };
  }
  const 效果: Extract<技能效果, { type: '施加状态' }> = {
    type: '施加状态',
    目标,
    状态,
    层数: 层数规格[阶层],
  };
  if (!纯层数状态.has(状态) && !永久) 效果.持续回合数 = 持续回合规格[阶层];
  return 效果;
}

/** 为一个战斗技能造命中效果 (按配方轮换, 保证同角色各技能不同) */
function 造命中效果(配方: number, 罪孽: 罪孽名, 阶层: 阶层名, 种子: number, 永久: boolean): 技能效果[] {
  const DoT = 罪孽DoT[罪孽];
  switch (配方) {
    case 0:
      return [状态效果('敌人', DoT, 阶层)];
    case 1:
      return [状态效果('敌人', 取子项(持续减益池, 种子), 阶层, 永久)];
    case 2:
      return [
        { type: '条件增伤', 条件: 取子项(['生命低于50%', '生命未满', '沉沦>0', '未混乱'], 种子), 数值: 20 + 阶层索引(阶层) * 5 },
        状态效果('敌人', 取子项(持续减益池, 种子 >> 2), 阶层),
      ];
    case 3:
      return [
        状态效果('自己', 取子项(持续增益池, 种子), 阶层, 永久),
        状态效果('敌人', DoT, 阶层),
      ];
    default:
      return [
        { type: '震颤引爆', 目标: '敌人' },
        状态效果('敌人', DoT, 阶层),
      ];
  }
}


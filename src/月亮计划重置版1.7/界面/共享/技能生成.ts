/**
 * 按 身份 + 阶层 + 关键词 生成一整套规范化技能 (N 战斗 + 1 守备 + 1 支援 + 1 被动)。
 * 关键词优先 (来自正文 AI), 缺失时回退内置身份主题。同 (身份, 阶层, 关键词) 生成确定。
 */
export function 按身份阶层生成技能(身份: string, 阶层: 阶层名, 等级: number, 关键词文本?: string): 生成技能集 {
  const 关键词 = 解析技能关键词(关键词文本);
  const 内置 = 选内置主题(身份);

  const 罪孽池 = 关键词.罪孽.length > 0 ? 关键词.罪孽 : 内置.罪孽;
  const 攻击池 = 内置.攻击.length > 0 ? 内置.攻击 : 攻击类型列表;
  const 意象池 = [...关键词.主题, ...关键词.性格, ...内置.意象].filter(Boolean);
  const 名称候选 = [...关键词.技能名];

  const 已用 = new Set<string>();
  const 技能: 技能定义[] = [];
  const 点数表 = 战斗技能点数规格[阶层] ?? 战斗技能点数规格.普通;
  const 硬币表 = 战斗硬币数规格[阶层] ?? 战斗硬币数规格.普通;
  void 等级;

  for (let i = 0; i < 点数表.length; i++) {
    const 种子 = 散列(`${身份}|${阶层}|战技|${i}|${关键词文本 ?? ''}`);
    const 名称 = 取名(名称候选, 意象池, 种子, 已用, `战技${i + 1}`);
    const 罪孽 = 取子项(罪孽池, 种子 + i);
    const 攻击类型 = 取子项(攻击池, 种子 >> 3);
    const { 基础威力, 硬币 } = 造硬币(点数表[i], 硬币表[i % 硬币表.length], 可含红币[阶层], 种子);
    const 永久 = 阶层 === '神话' && i === 0;
    const 命中效果 = 造命中效果(i % 5, 罪孽, 阶层, 种子, 永久);
    const 硬币定义 = 硬币.map((c, idx) => ({
      威力: c.威力,
      类型: c.类型,
      命中效果: idx === 硬币.length - 1 ? 命中效果 : [],
    }));
    技能.push(
      规范化技能定义({
        名称,
        类别: '战斗',
        罪孽,
        攻击类型,
        基础威力,
        硬币: 硬币定义,
        攻击等级修正: 0,
        攻击容量: 1,
        描述: `${阶层}·原创战斗技能（主题：${意象池.slice(0, 3).join('、') || 身份}）。`,
      }),
    );
  }

  // 守备 (带效果)
  {
    const 种子 = 散列(`${身份}|${阶层}|守备|${关键词文本 ?? ''}`);
    const 名称 = 取名([], 意象池, 种子, 已用, `${身份}守备`);
    const 点数 = 守备点数规格[阶层] ?? 10;
    const 基础威力 = Math.max(3, Math.round(点数 * 0.5));
    const 守备类型 = 取子项<守备类型名>(['防御', '闪避', '强化防御', '反击'] as const, 种子);
    const 守备效果: 技能效果[] =
      守备类型 === '闪避'
        ? [状态效果('自己', '迅捷', 阶层)]
        : 守备类型 === '反击'
          ? [状态效果('自己', '攻击等级提升', 阶层)]
          : [{ type: '获得护盾', 目标: '自己', 数值: 4 + 阶层索引(阶层) * 3 }];
    技能.push(
      规范化技能定义({
        名称,
        类别: '守备',
        守备类型,
        罪孽: 取子项(罪孽池, 种子),
        攻击类型: 取子项(攻击池, 种子 >> 3),
        基础威力,
        硬币: [{ 威力: Math.max(1, 点数 - 基础威力), 类型: '普通', 命中效果: 守备效果 }],
        攻击等级修正: 0,
        攻击容量: 1,
        描述: `${阶层}·原创守备（${守备类型}）。`,
      }),
    );
  }

  // 支援 (条件 + 多效果)
  {
    const 种子 = 散列(`${身份}|${阶层}|支援|${关键词文本 ?? ''}`);
    const 名称 = 取名([], 意象池, 种子, 已用, `${身份}支援`);
    const 时机 = 取子项(['战斗开始时', '回合开始时', '常驻'] as const, 种子);
    const 效果A = 状态效果('全体盟友', 取子项(['强壮', '攻击等级提升', '伤害强化', '守护'], 种子), 阶层);
    const 效果B = 状态效果('全体盟友', 取子项(['迅捷', '防御等级提升', '拼点威力提升'], 种子 >> 2), 阶层);
    const effects = 时机 === '常驻' ? [效果A] : [效果A, 效果B];
    技能.push(
      规范化技能定义({
        名称,
        类别: '支援',
        时机,
        effects,
        描述: `${阶层}·原创支援（${时机}）。`,
      }),
    );
  }

  // 被动 (条件 + 效果)
  {
    const 种子 = 散列(`${身份}|${阶层}|被动|${关键词文本 ?? ''}`);
    const 名称 = 取名([], 意象池, 种子, 已用, `${身份}被动`);
    const 时机 = 取子项(['回合开始时', '受击时', '命中时'] as const, 种子);
    const 状态 = 取子项(['强壮', '忍耐', '伤害强化', '充能', '攻击等级提升'], 种子);
    const effects = [状态效果('自己', 状态, 阶层)];
    技能.push(
      规范化技能定义({
        名称,
        类别: '被动',
        时机,
        每回合一次: 时机 === '回合开始时' ? undefined : true,
        effects,
        描述: `${阶层}·原创被动（${时机}）。`,
      }),
    );
  }

  return { 技能, 技能名: 技能.map(s => s.名称) };
}

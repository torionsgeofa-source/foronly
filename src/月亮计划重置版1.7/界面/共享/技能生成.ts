/** FNV-1a 文本散列 (确定性) */
function 散列(文本: string): number {
  let h = 2166136261;
  for (let i = 0; i < 文本.length; i++) {
    h ^= 文本.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

function 取子项<T>(数组: T[], 种子: number): T {
  return 数组[种子 % 数组.length];
}

/** 在名池中取一个未用过的技能名 (冲突则加数字后缀) */
function 取唯一名(池: string[], 已用: Set<string>, 兜底: string, 序号: number): string {
  const 基 = 池.length > 0 ? 池[序号 % 池.length] : 兜底;
  let 名 = 基;
  let n = 2;
  while (已用.has(名)) 名 = `${基}${n++}`;
  已用.add(名);
  return 名;
}

/** 由「点数目标 + 硬币枚数」派生 基础威力 与 各硬币威力 (Σ = 点数 - 基础威力) */
function 造硬币(点数: number, 硬币数: number, 含红币: boolean, 种子: number): { 基础威力: number; 硬币: { 威力: number; 类型: 硬币类型 }[] } {
  const 基础威力 = Math.max(3, Math.round(点数 * 0.4));
  const 硬币和 = Math.max(硬币数, 点数 - 基础威力);
  const 每枚 = Math.floor(硬币和 / 硬币数);
  const 余 = 硬币和 - 每枚 * 硬币数;
  const 硬币: { 威力: number; 类型: 硬币类型 }[] = [];
  for (let i = 0; i < 硬币数; i++) {
    const 红 = 含红币 && (i === 0 || (硬币数 >= 4 && i === 1));
    硬币.push({ 威力: 每枚 + (i < 余 ? 1 : 0), 类型: 红 ? '不可摧毁' : '普通' });
  }
  // 小扰动 (保持 Σ 不变), 避免同一技能各硬币全同
  if (硬币数 >= 2 && 种子 % 2 === 1 && 硬币[0].威力 > 1) {
    硬币[0].威力 -= 1;
    硬币[1].威力 += 1;
  }
  return { 基础威力, 硬币 };
}

function 合法状态名(状态: string, 兜底: string): string {
  return 合法状态.has(状态) ? 状态 : 兜底;
}


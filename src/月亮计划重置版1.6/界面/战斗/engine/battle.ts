/** 击杀敌人带来的 SP 变化 (含对全体友方) */
function 结算击杀SP(击杀者: 战斗单位, 被击杀者: 战斗单位, 全体: 战斗单位[]): SP变化记录[] {
  const 结果: SP变化记录[] = [];
  if (被击杀者.等级 >= 击杀者.等级) {
    const 实际 = 调整SP(击杀者, 10);
    SP记录(击杀者, 实际, 结果);
  }
  if (击杀者.阵营 !== '敌人') {
    for (const 友 of 全体) {
      if (!存活(友) || 友.阵营 === '敌人') continue;
      if (被击杀者.等级 >= 友.等级) {
        const 实际 = 调整SP(友, 5);
        SP记录(友, 实际, 结果);
      }
    }
  }
  return 结果;
}

/** 友方阵亡带来的 SP 惩罚 */
function 结算阵亡SP(阵亡者: 战斗单位, 全体: 战斗单位[]): SP变化记录[] {
  const 结果: SP变化记录[] = [];
  if (阵亡者.阵营 === '敌人') return 结果;
  for (const 友 of 全体) {
    if (友 === 阵亡者 || !存活(友) || 友.阵营 === '敌人') continue;
    if (阵亡者.等级 >= 友.等级) {
      const 差 = 阵亡者.等级 - 友.等级;
      const 实际 = 调整SP(友, -(10 + 差 * 10));
      SP记录(友, 实际, 结果);
    }
  }
  return 结果;
}


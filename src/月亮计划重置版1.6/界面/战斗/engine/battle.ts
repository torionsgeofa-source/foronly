function 守备文本(守备方: 战斗单位, 守备类型: 守备结算): string {
  switch (守备类型) {
    case '闪避':
      return `${守备方.名称} 闪避了攻击`;
    case '防御':
      return `${守备方.名称} 挡下攻击并进入防御姿态 (获得忍耐)`;
    case '强化防御':
      return `${守备方.名称} 以强化防御挡下攻击 (获得忍耐)`;
    case '反击':
      return `${守备方.名称} 反击`;
    case '强化反击':
      return `${守备方.名称} 强化反击`;
    default:
      return `${守备方.名称} 防住了攻击`;
  }
}


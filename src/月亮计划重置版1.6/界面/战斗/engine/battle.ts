/** 全场触发某一时机的被动 (自身) 与支援 (我方全体) */
export function 触发时机(战斗: 战斗状态, 时机: 技能时机, 记录 = true, rng: 随机源 = 默认随机源): void {
  for (const 单位 of 战斗.单位) 触发被动技能(战斗, 单位, 时机, 记录, rng);
  for (const 单位 of 战斗.单位) 触发支援技能(战斗, 单位, 时机, 记录, rng);
}

/** 仅按攻守双方单位触发某一时机 (命中时 / 受击时 / 击杀时) */
export function 触发单位时机(战斗: 战斗状态, 单位: 战斗单位, 时机: 技能时机, 记录 = true, rng: 随机源 = 默认随机源): void {
  触发被动技能(战斗, 单位, 时机, 记录, rng);
  触发支援技能(战斗, 单位, 时机, 记录, rng);
}

/**
 * 「损失理智时」被动 / 支援: 单位理智值下降时触发 (效果按各自 目标 结算)。
 * 标记「每回合一次」的技能每回合最多触发一次 (记录于 单位.每回合触发记录, 回合开始时清空)。
 */
function 触发损失理智(战斗: 战斗状态, 单位: 战斗单位, rng: 随机源): void {
  if (!存活(单位)) return;
  for (const 技能 of [...单位.被动技能, ...单位.支援技能]) {
    if (技能.时机 !== '损失理智时') continue;
    if (技能.每回合一次 && 单位.每回合触发记录?.[技能.名称]) continue;
    if (!满足条件(单位, 技能.条件)) continue;
    if (技能.每回合一次) {
      单位.每回合触发记录 ??= {};
      单位.每回合触发记录[技能.名称] = true;
    }
    执行效果(单位, 单位, 技能.效果, { 全体: 战斗.单位, 随机源: rng });
    战斗.日志.push(`[被动] ${单位.名称} 触发「${技能.名称}」`);
  }
}

/** 对照行动前快照, 为本回合理智下降的存活单位触发「损失理智时」被动 / 支援 */
function 结算损失理智触发(战斗: 战斗状态, 快照: Map<战斗单位, number>, rng: 随机源): void {
  for (const 单位 of 战斗.单位) {
    if (!存活(单位)) continue;
    const 前 = 快照.get(单位);
    if (前 === undefined || 单位.理智值 >= 前) continue;
    触发损失理智(战斗, 单位, rng);
  }
}

/**
 * 重算「常驻」光环: 先把基础属性复位, 清空常驻将施加的状态, 再重新施加一次,
 * 因此每回合调用都是幂等的。
 *
 * 幂等约束: 「常驻」仅结算「施加状态」效果。护盾 / 数值调整等非状态效果无法在每回合
 * 复位后重算 (复位护盾 / 生命 / SP 会抹掉正常战斗消耗), 故一律忽略并 warn,
 * 以保证常驻「获得护盾 / 调整数值」不会每回合重复叠加。
 */
export function 重算常驻光环(战斗: 战斗状态, 记录 = false, rng: 随机源 = 默认随机源): void {
  const 常驻状态名 = new Set<string>();
  const 已警告 = new Set<string>();
  const 收集 = (技能: (typeof 战斗.单位)[number]['被动技能'][number]) => {
    if (技能.时机 !== '常驻') return;
    for (const 效果 of 技能.效果) {
      if (效果.type === '施加状态') 常驻状态名.add(效果.状态);
      else if (!已警告.has(技能.名称)) {
        已警告.add(技能.名称);
        console.warn(`[战斗] 常驻技能「${技能.名称}」包含非「施加状态」效果, 已忽略以保证幂等`);
      }
    }
  };
  for (const 单位 of 战斗.单位) {
    for (const 技能 of 单位.被动技能) 收集(技能);
    for (const 技能 of 单位.支援技能) 收集(技能);
  }
  for (const 单位 of 战斗.单位) {
    if (单位.基础属性) {
      单位.攻击等级 = 单位.基础属性.攻击等级;
      单位.防御等级 = 单位.基础属性.防御等级;
    }
    for (const 名称 of 常驻状态名) delete 单位.状态效果[名称];
  }
  // 只重新施加「施加状态」效果, 其余类型已在上面忽略
  for (const 单位 of 战斗.单位) {
    if (!存活(单位)) continue;
    for (const 技能 of [...单位.被动技能, ...单位.支援技能]) {
      if (技能.时机 !== '常驻') continue;
      if (!满足条件(单位, 技能.条件)) continue;
      const 状态效果 = 技能.效果.filter(效果 => 效果.type === '施加状态');
      if (状态效果.length === 0) continue;
      执行效果(单位, 单位, 状态效果, { 全体: 战斗.单位, 随机源: rng });
      if (记录) 战斗.日志.push(`[常驻] ${单位.名称} 触发「${技能.名称}」`);
    }
  }
}


/**
 * 技能库插件 (独立脚本)
 *
 * - 内置一套规范化技能 DB (战斗 / 守备 / 被动 / 支援 / EGO);
 * - 玩家通过 `增 / 改 / 删 / 导入` 的改动写入全局变量 `技能库` 的键 (覆盖层), 读取时按 默认库 + 全局覆盖 合并;
 * - 通过 `initializeGlobal('技能库', api)` 向战斗 / 状态栏 / 开局表单等前端界面暴露统一接口。
 *
 * 本插件不依赖任何角色卡 schema 或变量结构, 可被其它卡 / 版本复用。
 *
 * 为保证共享接口一定初始化成功, 本文件是"纯核心": 不含任何 Vue / pinia /
 * App.vue / 界面目录 / @util/script 的静态 import, 也不含任何外部依赖。
 * 悬浮窗等界面逻辑已拆分到独立脚本 `脚本\技能库界面\index.ts`。
 */

/* ------------------------------------------------------------------ *
 * 类型 (与 engine/types.ts 的 技能 / 模板 结构保持一致)
 * ------------------------------------------------------------------ */

type 罪孽名 = '暴怒' | '色欲' | '怠惰' | '暴食' | '忧郁' | '傲慢' | '嫉妒';
type 攻击类型名 = '斩击' | '突刺' | '打击';
type 硬币类型 = '普通' | '不可摧毁' | '截除' | '无我';
type 技能类别 = '战斗' | '守备' | '被动' | '支援' | 'EGO';
type 守备类型名 = '闪避' | '防御' | '强化防御' | '反击' | '强化反击';
type 技能时机 = '战斗开始时' | '回合开始时' | '回合结束时' | '命中时' | '受击时' | '击杀时' | '常驻';

type 数值调整 = { 生命?: number; SP?: number; 攻击等级?: number; 防御等级?: number };

type 技能效果 =
  | { type: '施加状态'; 状态: string; 强度?: number; 层数?: number }
  | { type: '调整数值'; 数值: 数值调整 }
  | { type: '震颤引爆' }
  | { type: '获得护盾'; 数值: number }
  | { type: '条件增伤'; 条件: string; 数值: number };

interface 战斗技能硬币 {
  威力: number;
  类型: 硬币类型;
  命中效果?: 技能效果[];
}

/** 技能库中的单条技能定义 */
export interface 技能定义 {
  名称: string;
  类别: 技能类别;
  罪孽?: 罪孽名;
  攻击类型?: 攻击类型名;
  守备类型?: 守备类型名;
  时机?: 技能时机;
  条件?: string;
  基础威力?: number;
  硬币威力?: number[];
  硬币类型?: 硬币类型[];
  硬币?: 战斗技能硬币[];
  攻击等级修正?: number;
  攻击容量?: number;
  效果?: string;
  SP消耗?: number;
  effects?: 技能效果[];
}

/** 暴露给其它前端界面 / 脚本的共享接口 */
export interface 技能库接口 {
  查(名: string): 技能定义 | undefined;
  全部(): Record<string, 技能定义>;
  内存列表(): 技能定义[];
  增(名: string, 定义: 技能定义): void;
  改(名: string, 定义: 技能定义): void;
  删(名: string): void;
  导入(json: string): void;
  导出(名?: string): string;
  重置(): void;
}


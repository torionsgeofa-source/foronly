function 推断守备(名称: string, 效果: string): { 类别: '战斗' | '守备'; 守备类型?: 守备类型名 } {
  const 文本 = `${名称} ${效果}`;
  const 规则: Array<[string, 守备类型名]> = [
    ['强化反击', '强化反击'],
    ['强化防御', '强化防御'],
    ['反击', '反击'],
    ['闪避', '闪避'],
    ['格挡', '防御'],
    ['招架', '防御'],
    ['防御', '防御'],
  ];
  for (const [关键词, 类型] of 规则) {
    if (文本.includes(关键词)) return { 类别: '守备', 守备类型: 类型 };
  }
  return { 类别: '战斗' };
}

const 合法罪孽 = new Set<string>(罪孽列表);
const 合法攻击类型 = new Set<string>(攻击类型列表);
const 合法硬币类型 = new Set<string>(硬币类型列表);
const 合法类别 = new Set<string>(['战斗', '守备', '被动', '支援', 'EGO']);
const 合法时机 = new Set<string>(['战斗开始时', '回合开始时', '回合结束时', '命中时', '受击时', '击杀时', '常驻']);
const 合法守备类型 = new Set<string>(['闪避', '防御', '强化防御', '反击', '强化反击']);

function 数值夹取(v: unknown, 最小: number, 最大: number, 默认: number): number {
  const n = Number(v);
  if (!Number.isFinite(n)) return 默认;
  return Math.min(最大, Math.max(最小, n));
}


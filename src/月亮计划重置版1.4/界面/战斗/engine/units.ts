/** 兼容旧 API: 由散字段构造运行时技能; 若提供 硬币 则优先由其派生 硬币威力/硬币类型 */
export function 构造技能(数据: {
  名称: string;
  基础威力: number;
  硬币威力?: number[];
  硬币?: 战斗技能硬币[];
  罪孽?: 罪孽名;
  攻击类型?: 攻击类型名;
  硬币类型?: 硬币类型[];
  攻击等级修正?: number;
  攻击容量?: number;
  效果?: string;
  类别?: 技能类别;
  时机?: 技能时机;
  条件?: string;
  守备类型?: 守备类型名;
  SP消耗?: number;
  effects?: 技能效果[];
}): 技能 {
  const 类别 = 数据.类别 ?? '战斗';
  const 硬币: 战斗技能硬币[] =
    数据.硬币 ?? (数据.硬币威力 ?? []).map(威力 => ({ 威力, 类型: '普通' as 硬币类型 }));
  return {
    名称: 数据.名称,
    罪孽: 数据.罪孽 ?? '暴怒',
    攻击类型: 数据.攻击类型 ?? '打击',
    基础威力: 数据.基础威力,
    硬币威力: 数据.硬币威力 ? [...数据.硬币威力] : 硬币.map(项 => 项.威力),
    硬币类型: 数据.硬币类型 ? [...数据.硬币类型] : 硬币.map(项 => 项.类型),
    硬币: 数据.硬币 ? 硬币.map(复制硬币) : undefined,
    攻击等级修正: 数据.攻击等级修正 ?? 0,
    攻击容量: 数据.攻击容量 ?? 1,
    效果: 数据.效果 ?? '',
    类别,
    时机: 数据.时机,
    条件: 数据.条件,
    守备类型: 数据.守备类型,
    SP消耗: 数据.SP消耗 ?? (类别 === 'EGO' ? 10 : 0),
    effects: 数据.effects ? 数据.effects.map(效果 => ({ ...效果 })) : undefined,
  };
}

function 复制硬币(硬币: 战斗技能硬币): 战斗技能硬币 {
  return {
    威力: 硬币.威力,
    类型: 硬币.类型,
    命中效果: 硬币.命中效果 ? 硬币.命中效果.map(效果 => ({ ...效果 })) : undefined,
  };
}


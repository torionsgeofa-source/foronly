function 复制被动技能(技能: 被动技能模板): 被动技能模板 {
  return { ...技能, 效果: 技能.效果.map(效果 => ({ ...效果 })) };
}

function 复制支援技能(技能: 支援技能模板): 支援技能模板 {
  return { ...技能, 效果: 技能.效果.map(效果 => ({ ...效果 })) };
}

/** 未命中技能库时的占位技能 (标准化兜底并警告) */
function 补占位技能(名: string): 技能 {
  const { 技能, 修复 } = 标准化技能(名, {});
  console.warn(`[技能库] 技能「${名}」未在技能库中找到, 已用占位技能${修复.length > 0 ? `: ${修复.join('; ')}` : ''}`);
  return 技能;
}

/** 解析人格模板中的战斗技能名 (从技能库取定义, 人格模板为内置, 按「通用」解析) */
function 解析模板战斗技能(模板: 人格模板, 角色: string = 通用角色): Record<string, 技能> {
  const 技能表: Record<string, 技能> = {};
  for (const 名 of 模板.战斗技能) {
    const 技能 = 查库技能(名, 角色) ?? 补占位技能(名);
    技能表[技能.名称] = 技能;
  }
  return 技能表;
}

function 解析模板被动技能(模板: 人格模板, 角色: string = 通用角色): 被动技能模板[] {
  return 模板.被动技能
    .map(名 => 查库被动(名, 角色))
    .filter((项): 项 is 被动技能模板 => !!项)
    .map(复制被动技能);
}

function 解析模板支援技能(模板: 人格模板, 角色: string = 通用角色): 支援技能模板[] {
  return 模板.支援技能
    .map(名 => 查库支援(名, 角色))
    .filter((项): 项 is 支援技能模板 => !!项)
    .map(复制支援技能);
}


/**
 * 将变量中的技能解析为引擎技能:
 * - 变量现只保存技能名 (string[]); 先按 `角色名` 命中技能库, 未命中回退「通用」;
 * - 仍未命中 → 用标准化技能占位并 warn (兼容旧对象写法时采用其字段).
 */
export function 技能记录转技能(记录: string[] | 技能记录, 角色名: string = 通用角色): Record<string, 技能> {
  const 结果: Record<string, 技能> = {};
  const 条目: Array<[string, Record<string, unknown>]> = Array.isArray(记录)
    ? 记录.filter(名 => typeof 名 === 'string' && 名.trim()).map(名 => [名, {}])
    : Object.entries(记录 ?? {}).map(([名, 原始]) => [名, (原始 ?? {}) as Record<string, unknown>]);

  for (const [名称, 原始] of 条目) {
    const 库技能 = 查库技能(名称, 角色名);
    if (库技能) {
      结果[名称] = 库技能;
      continue;
    }
    const { 技能, 修复 } = 标准化技能(名称, 原始);
    console.warn(
      `[技能库] 技能「${名称}」未在技能库中找到, 已用占位技能${修复.length > 0 ? `: ${修复.join('; ')}` : ''}`,
    );
    结果[名称] = 技能;
  }
  return 结果;
}

/** 根据身份找一个模板, 找不到则用收尾人模板兜底 */
export function 查找模板(身份: string): 人格模板 {
  return 敌人库[身份] ?? 身份库[身份] ?? 身份库.收尾人;
}

/** 为缺少技能/被动/支援的 AI 单位补齐该身份的默认配置 */
export function 补齐技能(单位: 战斗单位): 战斗单位 {
  const 模板 = 查找模板(单位.身份);
  if (Object.keys(单位.技能).length === 0) 单位.技能 = 解析模板战斗技能(模板, 单位.名称);
  if (!单位.被动技能 || 单位.被动技能.length === 0) 单位.被动技能 = 解析模板被动技能(模板, 单位.名称);
  if (!单位.支援技能 || 单位.支援技能.length === 0) 单位.支援技能 = 解析模板支援技能(模板, 单位.名称);
  if (!单位.基础属性) 单位.基础属性 = { 攻击等级: 单位.攻击等级, 防御等级: 单位.防御等级 };
  return 单位;
}

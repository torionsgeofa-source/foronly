import type { 技能效果 } from './types';

/** 装备效果：技能效果之外，追加仅装备模式产出的「生命加成」标记（供 schema 求和最大生命） */
export type 装备效果 = 技能效果 | { type: '生命加成'; 数值: number };

/** 解析模式：技能模式不产出「生命加成」且拒绝「生命上限」；装备模式将 +N生命值 视作最大生命 */
type 解析模式 = '技能' | '装备';

/**
 * 引擎可识别的状态白名单。
 * 汇总自 engine/status.ts (自我增益/层数上限/聚合加成/DoT 触发)
 * 与 世界书 战斗规则 的 状态效果_通用 / 状态效果_DoT。
 */
export const 合法状态名: string[] = [
  // 通用 · 增益
  '强壮',
  '忍耐',
  '威力提升',
  '拼点威力提升',
  '攻击等级提升',
  '防御等级提升',
  '伤害强化',
  '守护',
  '迅捷',
  '暴击伤害强化',
  // 通用 · 减益
  '虚弱',
  '破绽',
  '威力降低',
  '拼点威力降低',
  '攻击等级降低',
  '防御等级降低',
  '伤害弱化',
  '易损',
  '束缚',
  '麻痹',
  // DoT / 资源
  '破裂',
  '震颤',
  '流血',
  '呼吸法',
  '充能',
  '沉沦',
  '烧伤',
];

const 合法状态集 = new Set(合法状态名);

/** 统一清洗: 全角数字/符号转半角、半角逗号归一为全角、去除所有空白 */
function 预清洗(文本: string): string {
  return 文本
    .replace(/[０-９]/g, ch => String.fromCharCode(ch.charCodeAt(0) - 0xfee0))
    .replace(/[＋]/g, '+')
    .replace(/[－ー−–—]/g, '-')
    .replace(/[％]/g, '%')
    .replace(/[：]/g, ':')
    .replace(/,/g, '，')
    .replace(/\s+/g, '');
}

/** 按 ; ； 。 \n 切分多条效果 */
function 切分(文本: string): string[] {
  return 文本
    .split(/[；;。\n\r]+/)
    .map(段 => 段.trim())
    .filter(Boolean);
}

function 构造施加状态(状态: string, 层数: number, 强度: number | undefined, 修复: string[], 原文: string): 技能效果 {
  if (!合法状态集.has(状态)) {
    修复.push(`未知状态名「${状态}」将被引擎忽略（来自「${原文}」）`);
  }
  return { type: '施加状态', 状态, 层数, 强度: 强度 ?? 0 };
}

/** 解析单个片段; 无法识别时记录 修复 并返回 null */
function 解析片段(原文: string, 修复: string[], 模式: 解析模式 = '技能'): 装备效果 | null {
  const 文本 = 预清洗(原文);
  if (!文本) return null;

  // 装备模式: 最大生命的固定加成, 与技能的治疗 / 护盾区分
  if (模式 === '装备') {
    let 生 = 文本.match(/^(?:生命加成|生命上限)\+(\d+)$/);
    if (生) return { type: '生命加成', 数值: Number(生[1]) };
    生 = 文本.match(/^\+(\d+)点?生命值$/);
    if (生) return { type: '生命加成', 数值: Number(生[1]) };
    生 = 文本.match(/^生命值\+(\d+)$/);
    if (生) return { type: '生命加成', 数值: Number(生[1]) };
  }

  // 战斗中不修改生命上限: 含「生命上限」的写法一律按无法识别片段处理, 不生成任何效果。
  if (文本.includes('生命上限')) {
    修复.push(`无法识别的效果片段「${原文}」`);
    return null;
  }

  // 条件增伤: 当<条件>时伤害+<N>% (兼容「造成伤害」「增加」)
  let 匹配 = 文本.match(/^当(.+?)时(?:造成)?伤害(?:增加|\+)(\d+)%$/);
  if (匹配) return { type: '条件增伤', 条件: 匹配[1], 数值: Number(匹配[2]) };

  // 震颤引爆
  if (文本 === '震颤引爆') return { type: '震颤引爆' };

  // 护盾 · 规范: 获得N点护盾 / 获得护盾N
  匹配 = 文本.match(/^(?:获得(\d+)点?护盾|获得护盾(\d+))$/);
  if (匹配) return { type: '获得护盾', 数值: Number(匹配[1] ?? 匹配[2]) };

  // 容错: 施加N层护盾 → 获得 N×10 点护盾 (每层 10 点)
  匹配 = 文本.match(/^施加(\d+)层护盾$/);
  if (匹配) {
    const 点数 = Number(匹配[1]) * 10;
    修复.push(`「${原文}」→ 获得护盾${点数} (每层 10 点)`);
    return { type: '获得护盾', 数值: 点数 };
  }

  // 数值: 恢复/失去 N 点 生命 / SP
  匹配 = 文本.match(/^(恢复|失去)(\d+)点?(生命|SP)$/i);
  if (匹配) {
    const 变化 = Number(匹配[2]) * (匹配[1] === '恢复' ? 1 : -1);
    if (匹配[3].toUpperCase() === 'SP') return { type: '调整数值', 数值: { SP: 变化 } };
    return { type: '调整数值', 数值: { 生命: 变化 } };
  }

  // 施加状态 · 数字在前: 施加N层状态[，强度M]
  匹配 = 文本.match(/^施加(\d+)层(.+?)(?:，?强度(\d+))?$/);
  if (匹配) return 构造施加状态(匹配[2], Number(匹配[1]), 匹配[3] ? Number(匹配[3]) : undefined, 修复, 原文);

  // 施加状态 · 状态在前 (容错): 施加状态N层[，强度M]
  匹配 = 文本.match(/^施加(.+?)(\d+)层(?:，?强度(\d+))?$/);
  if (匹配) return 构造施加状态(匹配[1], Number(匹配[2]), 匹配[3] ? Number(匹配[3]) : undefined, 修复, 原文);

  // 容错: 速度±N → 迅捷 / 束缚
  匹配 = 文本.match(/^速度([+-])(\d+)$/);
  if (匹配) {
    const 状态 = 匹配[1] === '+' ? '迅捷' : '束缚';
    修复.push(`「${原文}」→ 施加${匹配[2]}层${状态}`);
    return { type: '施加状态', 状态, 层数: Number(匹配[2]), 强度: 0 };
  }

  // 容错: 攻击等级±N → 攻击等级提升 / 降低
  匹配 = 文本.match(/^攻击等级([+-])(\d+)$/);
  if (匹配) {
    const 状态 = 匹配[1] === '+' ? '攻击等级提升' : '攻击等级降低';
    修复.push(`「${原文}」→ 施加${匹配[2]}层${状态}`);
    return { type: '施加状态', 状态, 层数: Number(匹配[2]), 强度: 0 };
  }

  // 容错: 防御等级±N → 防御等级提升 / 降低
  匹配 = 文本.match(/^防御等级([+-])(\d+)$/);
  if (匹配) {
    const 状态 = 匹配[1] === '+' ? '防御等级提升' : '防御等级降低';
    修复.push(`「${原文}」→ 施加${匹配[2]}层${状态}`);
    return { type: '施加状态', 状态, 层数: Number(匹配[2]), 强度: 0 };
  }

  修复.push(`无法识别的效果片段「${原文}」`);
  return null;
}

/** 将单条结构化效果转回规范语句 */
export function 序列化效果(效果: 技能效果): string {
  switch (效果.type) {
    case '施加状态': {
      const 强度 = 效果.强度 && 效果.强度 > 0 ? `，强度${效果.强度}` : '';
      return `施加${效果.层数 ?? 1}层${效果.状态}${强度}`;
    }
    case '调整数值': {
      const 段: string[] = [];
      const 数 = 效果.数值;
      if (数.生命 !== undefined) 段.push(数.生命 >= 0 ? `恢复${数.生命}点生命` : `失去${-数.生命}点生命`);
      if (数.SP !== undefined) 段.push(数.SP >= 0 ? `恢复${数.SP}点SP` : `失去${-数.SP}点SP`);
      if (数.攻击等级 !== undefined) 段.push(数.攻击等级 >= 0 ? `攻击等级+${数.攻击等级}` : `攻击等级${数.攻击等级}`);
      if (数.防御等级 !== undefined) 段.push(数.防御等级 >= 0 ? `防御等级+${数.防御等级}` : `防御等级${数.防御等级}`);
      return 段.join('，') || '数值调整';
    }
    case '震颤引爆':
      return '震颤引爆';
    case '获得护盾':
      return `获得${效果.数值}点护盾`;
    case '条件增伤':
      return `当${效果.条件}时伤害+${效果.数值}%`;
  }
}

/** 将单条结构化效果 (含装备独有) 转回规范语句 */
function 序列化单条(效果: 装备效果): string {
  if (效果.type === '生命加成') return `生命加成+${效果.数值}`;
  return 序列化效果(效果);
}

/** 解析一段 (可含多条) 技能效果文本为结构化效果；无法识别的片段记入 修复, 不抛错 */
export function 解析效果(文本: string): { 效果: 技能效果[]; 修复: string[] } {
  const 修复: string[] = [];
  const 效果: 技能效果[] = [];
  for (const 段 of 切分(文本)) {
    const 单条 = 解析片段(段, 修复, '技能');
    if (单条 && 单条.type !== '生命加成') 效果.push(单条);
  }
  return { 效果, 修复 };
}

/** 解析一段装备效果文本为结构化效果；+N生命值 类片段产出「生命加成」标记 */
export function 解析装备效果(文本: string): { 效果: 装备效果[]; 修复: string[] } {
  const 修复: string[] = [];
  const 效果: 装备效果[] = [];
  for (const 段 of 切分(文本)) {
    const 单条 = 解析片段(段, 修复, '装备');
    if (单条) 效果.push(单条);
  }
  return { 效果, 修复 };
}

/** 将技能效果文本改写为规范语句; 多条用 ； 连接, 无法识别的片段原样保留 */
export function 规范化效果(文本: string): string {
  const 结果: string[] = [];
  for (const 段 of 切分(文本)) {
    const 单条 = 解析片段(段, [], '技能');
    结果.push(单条 && 单条.type !== '生命加成' ? 序列化效果(单条) : 段);
  }
  return 结果.join('；');
}

/** 将装备效果文本改写为规范语句：+N生命值 / 生命值+N / +N点生命值 → 生命加成+N */
export function 规范化装备效果(文本: string): string {
  const 结果: string[] = [];
  for (const 段 of 切分(文本)) {
    const 单条 = 解析片段(段, [], '装备');
    结果.push(单条 ? 序列化单条(单条) : 段);
  }
  return 结果.join('；');
}

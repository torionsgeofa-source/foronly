export function 存活(单位: 战斗单位): boolean {
  return 单位.生命值 > 0;
}

/** 每回合开始时在速度区间内掷速度 (无区间则使用固定速度) */
export function 掷本回合速度(单位: 战斗单位, rng: 随机源 = 默认随机源): void {
  if (单位.速度区间) {
    const 最小 = Math.max(1, Math.round(单位.速度区间.最小));
    const 最大 = Math.max(最小, Math.round(单位.速度区间.最大));
    单位.本回合速度 = 随机整数(最小, 最大, rng);
  } else {
    单位.本回合速度 = Math.max(1, 单位.速度);
  }
}

export function 有效速度(单位: 战斗单位): number {
  return Math.max(1, 单位.本回合速度 + 聚合加成(单位).速度);
}

export function 敌对(左: 战斗单位, 右: 战斗单位): boolean {
  return (左.阵营 === '敌人') !== (右.阵营 === '敌人');
}

export function EGO资源消耗(技能: 技能): number {
  return 技能.资源消耗 ?? 3;
}

export function EGOSP消耗(技能: 技能): number {
  return 技能.SP消耗 ?? 10;
}

/** 是否满足使用 E.G.O 的条件: 对应罪孽资源足够, 且 SP > -45 */
export function 可用EGO(单位: 战斗单位, 技能: 技能): boolean {
  if (技能.类别 !== 'EGO') return true;
  return (单位.罪孽资源[技能.罪孽] ?? 0) >= EGO资源消耗(技能) && 单位.理智值 > -45;
}

export function 计算速度顺序(单位: 战斗单位[], rng: 随机源 = 默认随机源): string[] {
  return 单位
    .filter(存活)
    .map(单位 => ({ 名称: 单位.名称, 速度: 有效速度(单位), 随机: rng() }))
    .sort((左, 右) => 右.速度 - 左.速度 || 右.随机 - 左.随机)
    .map(项 => 项.名称);
}

export function 创建战斗状态(单位: 战斗单位[], rng: 随机源 = 默认随机源): 战斗状态 {
  const 顺序 = 计算速度顺序(单位, rng);
  return {
    单位,
    回合: 1,
    速度顺序: 顺序,
    当前行动者: 顺序[0] ?? '',
    行动指针: 0,
    日志: ['战斗开始'],
    结束: null,
  };
}

export function 当前单位(战斗: 战斗状态): 战斗单位 | undefined {
  return 战斗.单位.find(单位 => 单位.名称 === 战斗.速度顺序[战斗.行动指针]);
}

function 选择AI技能(单位: 战斗单位, rng: 随机源): 技能 | null {
  const 技能列表 = Object.values(单位.技能);
  if (技能列表.length === 0) return null;
  const 攻击技能 = 技能列表.filter(技能 => 技能.类别 === '攻击');
  const 守备技能 = 技能列表.filter(技能 => 技能.类别 === '守备');
  const EGO技能 = 技能列表.filter(技能 => 技能.类别 === 'EGO' && 可用EGO(单位, 技能));
  if (单位.生命值 <= 单位.生命上限 * 0.3 && 守备技能.length > 0 && rng() < 0.35) {
    return 守备技能[随机整数(0, 守备技能.length - 1, rng)];
  }
  if (EGO技能.length > 0 && rng() < 0.3) {
    return EGO技能[随机整数(0, EGO技能.length - 1, rng)];
  }
  const 池 = 攻击技能.length > 0 ? 攻击技能 : 技能列表;
  return 池[随机整数(0, 池.length - 1, rng)];
}

/** AI 自动选择攻击容量内的多个目标 */
function 选择AI目标列表(单位: 战斗单位, 全体: 战斗单位[], 容量: number, rng: 随机源): string[] {
  const 敌人列表 = 全体.filter(目标 => 敌对(单位, 目标) && 存活(目标));
  const 结果: string[] = [];
  const 上限 = Math.max(1, Math.floor(容量));
  while (结果.length < 上限 && 敌人列表.length > 0) {
    const 下标 = 随机整数(0, 敌人列表.length - 1, rng);
    结果.push(敌人列表[下标].名称);
    敌人列表.splice(下标, 1);
  }
  return 结果;
}

/** 所有非玩家单位自动选择技能与目标 */
export function 准备回合(战斗: 战斗状态, rng: 随机源 = 默认随机源): void {
  for (const 单位 of 战斗.单位) {
    单位.已选技能 = null;
    单位.已选目标 = [];
    单位.已行动 = false;
    if (存活(单位)) {
      掷本回合速度(单位, rng);
      更新士气低落(单位);
    }
  }
  for (const 单位 of 战斗.单位) {
    if (单位.是否玩家 || !存活(单位)) continue;
    const 技能 = 选择AI技能(单位, rng);
    if (!技能) continue;
    单位.已选技能 = 技能.名称;
    单位.已选目标 = 选择AI目标列表(单位, 战斗.单位, 技能.攻击容量, rng);
  }
  const 共鸣日志 = 结算罪孽共鸣(战斗.单位);
  战斗.日志.push(...共鸣日志);
  战斗.速度顺序 = 计算速度顺序(战斗.单位, rng);
  战斗.行动指针 = 0;
  战斗.当前行动者 = 战斗.速度顺序[0] ?? '';
}

function 掷出攻击硬币(技能: 技能, 单位: 战斗单位, rng: 随机源) {
  const 硬币列表 = 构建硬币(技能);
  const 概率 = 正面率(单位.理智值);
  for (const 硬币 of 硬币列表) {
    硬币.正面 = 掷硬币(概率, rng);
  }
  return 硬币列表;
}

function SP记录(单位: 战斗单位, 变化: number, 列表: SP变化记录[]): void {
  if (变化 !== 0) 列表.push({ 名称: 单位.名称, 变化 });
}

/** 击杀敌人带来的 SP 变化 (含对全体友方) */
function 结算击杀SP(击杀者: 战斗单位, 被击杀者: 战斗单位, 全体: 战斗单位[]): SP变化记录[] {
  const 结果: SP变化记录[] = [];
  if (被击杀者.等级 >= 击杀者.等级) {
    const 实际 = 调整SP(击杀者, 10);
    SP记录(击杀者, 实际, 结果);
  }
  if (击杀者.阵营 !== '敌人') {
    for (const 友 of 全体) {
      if (!存活(友) || 友.阵营 === '敌人') continue;
      if (被击杀者.等级 >= 友.等级) {
        const 实际 = 调整SP(友, 5);
        SP记录(友, 实际, 结果);
      }
    }
  }
  return 结果;
}

/** 友方阵亡带来的 SP 惩罚 */
function 结算阵亡SP(阵亡者: 战斗单位, 全体: 战斗单位[]): SP变化记录[] {
  const 结果: SP变化记录[] = [];
  if (阵亡者.阵营 === '敌人') return 结果;
  for (const 友 of 全体) {
    if (友 === 阵亡者 || !存活(友) || 友.阵营 === '敌人') continue;
    if (阵亡者.等级 >= 友.等级) {
      const 差 = 阵亡者.等级 - 友.等级;
      const 实际 = 调整SP(友, -(10 + 差 * 10));
      SP记录(友, 实际, 结果);
    }
  }
  return 结果;
}

function 无攻击结果(
  来源: 战斗单位,
  目标: 战斗单位,
  技能: 技能,
  拼点结果: 拼点结果 | undefined,
  文本: string,
  SP变化: SP变化记录[] = [],
  侵蚀 = false,
): 命中结果 {
  return {
    来源: 来源.名称,
    目标: 目标.名称,
    技能: 技能.名称,
    拼点: 拼点结果,
    伤害: [],
    追加: [],
    文本,
    目标死亡: 目标.生命值 <= 0,
    目标混乱: 是否混乱(目标),
    SP变化: SP变化.length > 0 ? SP变化 : undefined,
    侵蚀: 侵蚀 || undefined,
  };
}

function 跳过结果(单位: 战斗单位, 文本: string): 命中结果 {
  return {
    来源: 单位.名称,
    目标: 单位.名称,
    技能: '',
    伤害: [],
    追加: [],
    文本,
    目标死亡: false,
    目标混乱: 是否混乱(单位),
    跳过行动: true,
  };
}

/** 拼点序列产生的 SP 变化转换为记录 */
function 拼点SP记录(拼点结果: 拼点结果, 左侧: 战斗单位, 右侧: 战斗单位): SP变化记录[] {
  const 结果: SP变化记录[] = [];
  SP记录(左侧, 拼点结果.左侧SP变化, 结果);
  SP记录(右侧, 拼点结果.右侧SP变化, 结果);
  return 结果;
}

function 守备文本(守备方: 战斗单位, 守备类型: 守备结算): string {
  switch (守备类型) {
    case '闪避':
      return `${守备方.名称} 闪避了攻击`;
    case '防御':
      return `${守备方.名称} 挡下攻击并进入防御姿态 (获得忍耐)`;
    case '强化防御':
      return `${守备方.名称} 以强化防御挡下攻击 (获得忍耐)`;
    case '反击':
      return `${守备方.名称} 反击`;
    case '强化反击':
      return `${守备方.名称} 强化反击`;
    default:
      return `${守备方.名称} 防住了攻击`;
  }
}

interface 单目标输入 {
  战斗: 战斗状态;
  行动者: 战斗单位;
  技能: 技能;
  目标: 战斗单位;
  rng: 随机源;
  侵蚀?: boolean;
}

/** 结算行动者对单个目标的一次拼点/命中 */
function 解决单目标(输入: 单目标输入): 命中结果 {
  const { 战斗, 行动者, 技能, 目标, rng, 侵蚀 = false } = 输入;
  const 侵蚀标记 = 侵蚀 ? '【侵蚀】' : '';

  const 目标技能名 = 目标.已选技能;
  const 目标技能 = 目标技能名 ? 目标.技能[目标技能名] : undefined;
  const 目标索引 = 战斗.速度顺序.indexOf(目标.名称);
  const 目标技能是守备 = 目标技能?.类别 === '守备';
  const 会拼点 = !!目标技能 && (目标索引 > 战斗.行动指针 || 目标技能是守备);

  let 拼点结果: 拼点结果 | undefined;
  let 攻击方 = 行动者;
  let 受击方 = 目标;
  let 守备结果: 守备结算 | undefined;
  let SP变化: SP变化记录[] = [];

  if (会拼点 && 目标技能) {
    拼点结果 = 拼点(行动者, 技能, 目标, 目标技能, rng);
    SP变化 = 拼点SP记录(拼点结果, 行动者, 目标);
    // 防守方技能被消耗 (普通技能同样产生 1 点罪孽资源)
    目标.已选技能 = null;
    目标.已选目标 = [];
    目标.已行动 = true;
    if (目标技能.类别 !== 'EGO') 增加罪孽资源(目标, 目标技能.罪孽, 1);

    if (拼点结果.胜者 === '无') {
      const 文本 = `${侵蚀标记}${行动者.名称} 与 ${目标.名称} 拼点僵持, 均未受创`;
      战斗.日志.push(文本);
      return 无攻击结果(行动者, 目标, 技能, 拼点结果, 文本, SP变化, 侵蚀);
    }

    const 胜方单位 = 拼点结果.胜者 === '左' ? 行动者 : 目标;
    const 胜方技能 = 拼点结果.胜者 === '左' ? 技能 : 目标技能;
    const 胜方守备 = 胜方技能.守备类型;
    if (胜方守备 && 可拼点守备列表.includes(胜方守备)) {
      // 守备方胜利: 闪避/防御/强化防御
      if (胜方守备 === '防御' || 胜方守备 === '强化防御') {
        增加状态(胜方单位, '忍耐', 0, 胜方守备 === '防御' ? 2 : 3);
      }
      const 文本 = `${侵蚀标记}${守备文本(胜方单位, 胜方守备)}`;
      战斗.日志.push(文本);
      const 败方 = 胜方单位 === 行动者 ? 目标 : 行动者;
      return {
        来源: 胜方单位.名称,
        目标: 败方.名称,
        技能: 胜方技能.名称,
        拼点: 拼点结果,
        伤害: [],
        追加: [],
        文本,
        目标死亡: 败方.生命值 <= 0,
        目标混乱: 是否混乱(败方),
        守备结果: 胜方守备,
        SP变化: SP变化.length > 0 ? SP变化 : undefined,
        侵蚀: 侵蚀 || undefined,
      };
    }

    // 攻击方胜利 (普通攻击或反击)
    if (拼点结果.胜者 === '右') {
      攻击方 = 目标;
      受击方 = 行动者;
    }
    if (胜方技能.守备类型 === '反击' || 胜方技能.守备类型 === '强化反击') 守备结果 = 胜方技能.守备类型;
  }

  const 攻击技能 = 攻击方 === 行动者 ? 技能 : (目标技能 ?? 技能);
  const 硬币列表 = 拼点结果
    ? (攻击方 === 行动者 ? 拼点结果.左侧剩余硬币 : 拼点结果.右侧剩余硬币)
    : 掷出攻击硬币(攻击技能, 攻击方, rng);

  const 加成 = 聚合加成(攻击方);
  const 拼点回合数 = 拼点结果 ? 拼点结果.记录.length : 0;
  const 伤害列表: 伤害明细[] = [];
  const 全部追加: 追加伤害记录[] = [];
  const 受击前存活 = 存活(受击方);

  for (const 硬币 of 硬币列表) {
    if (硬币.已摧毁) continue;
    const 命中 = 硬币.已破碎 || 硬币.正面;
    if (!命中) continue;
    const 基础硬币威力 = (硬币.已破碎 ? 1 : 硬币.威力) + 加成.最终威力;
    const 触发结果 = 命中触发(攻击方, 受击方, rng);
    伤害列表.push(
      执行命中({
        攻击方,
        受击方,
        技能: 攻击技能,
        硬币威力: 基础硬币威力,
        拼点回合数,
        暴击: 触发结果.暴击,
        追加: 触发结果.追加,
      }),
    );
    全部追加.push(...触发结果.追加);
    if (!存活(受击方)) break;
  }

  // 击杀 / 阵亡 SP 结算
  if (受击前存活 && !存活(受击方)) {
    SP变化 = [...SP变化, ...结算击杀SP(攻击方, 受击方, 战斗.单位), ...结算阵亡SP(受击方, 战斗.单位)];
  }

  const 死亡 = 受击方.生命值 <= 0;
  const 总伤害 = 伤害列表.reduce((和, 项) => 和 + 项.数值, 0);
  const 拼点描述 = 拼点结果
    ? `拼点 ${拼点结果.记录.length} 回合(${拼点结果.胜者 === '左' ? 行动者.名称 : 拼点结果.胜者 === '右' ? 目标.名称 : '无果'}) `
    : '';
  const 守备描述 = 守备结果 ? `${守备结果} ` : '';
  const 暴击 = 伤害列表.some(项 => 项.暴击) ? '暴击! ' : '';
  const 死亡描述 = 死亡 ? `, ${受击方.名称} 倒下` : '';
  const 文本 = `${侵蚀标记}${攻击方.名称} 以 ${攻击技能.名称} ${拼点描述}${守备描述}对 ${受击方.名称} 造成 ${总伤害} 伤害${暴击 ? ` (${暴击.trim()})` : ''}${死亡描述}`;
  战斗.日志.push(文本);

  return {
    来源: 攻击方.名称,
    目标: 受击方.名称,
    技能: 攻击技能.名称,
    拼点: 拼点结果,
    伤害: 伤害列表,
    追加: 全部追加,
    文本,
    目标死亡: 死亡,
    目标混乱: 是否混乱(受击方),
    守备结果,
    侵蚀: 侵蚀 || undefined,
    SP变化: SP变化.length > 0 ? SP变化 : undefined,
  };
}

/** 结算当前行动者的行动; 玩家尚未选择技能/目标时返回 null。可能对多个目标分别结算。 */
export function 结算当前行动(战斗: 战斗状态, rng: 随机源 = 默认随机源): 命中结果[] | null {
  const 行动者 = 当前单位(战斗);
  if (!行动者 || !存活(行动者) || 行动者.已行动 || !行动者.已选技能) return null;

  const 技能 = 行动者.技能[行动者.已选技能];
  if (!技能) {
    行动者.已选技能 = null;
    return null;
  }

  // 恐慌 / 混乱: 跳过该回合行动
  if (行动者.恐慌状态 === '生效中') {
    行动者.已行动 = true;
    行动者.已选技能 = null;
    行动者.已选目标 = [];
    const 文本 = `${行动者.名称} 陷入恐慌, 无法行动`;
    战斗.日志.push(文本);
    return [跳过结果(行动者, 文本)];
  }
  if (是否混乱(行动者)) {
    行动者.已行动 = true;
    行动者.已选技能 = null;
    行动者.已选目标 = [];
    const 文本 = `${行动者.名称} 正处于混乱, 无法行动`;
    战斗.日志.push(文本);
    return [跳过结果(行动者, 文本)];
  }

  // E.G.O 资源检查 (UI 已置灰; 此处兜底)
  if (技能.类别 === 'EGO' && !可用EGO(行动者, 技能)) {
    行动者.已行动 = true;
    行动者.已选技能 = null;
    行动者.已选目标 = [];
    const 文本 = `${行动者.名称} 罪孽资源不足, 无法发动 ${技能.名称}`;
    战斗.日志.push(文本);
    return [跳过结果(行动者, 文本)];
  }

  // 主动使用闪避/防御: 不攻击, 架起守备等待被攻击 (防御额外获得忍耐)
  if (技能.类别 === '守备' && 技能.守备类型 && 可拼点守备列表.includes(技能.守备类型)) {
    行动者.已行动 = true;
    行动者.已选目标 = [];
    if (技能.守备类型 === '防御') 增加状态(行动者, '忍耐', 0, 2);
    if (技能.守备类型 === '强化防御') 增加状态(行动者, '忍耐', 0, 3);
    增加罪孽资源(行动者, 技能.罪孽, 1);
    const 文本 = `${行动者.名称} 摆出${技能.守备类型}姿态`;
    战斗.日志.push(文本);
    return [跳过结果(行动者, 文本)];
  }

  // E.G.O: 扣除资源与 SP, 并判定侵蚀 (支付后 SP ≤ -45)
  let 侵蚀 = false;
  if (技能.类别 === 'EGO') {
    消耗罪孽资源(行动者, 技能.罪孽, EGO资源消耗(技能));
    调整SP(行动者, -EGOSP消耗(技能));
    侵蚀 = 行动者.理智值 <= -45;
  } else {
    // 普通技能: 使用后 +1 对应罪孽资源
    增加罪孽资源(行动者, 技能.罪孽, 1);
  }

  // 消耗资源强化: 发动前若资源足够则消耗并提升本次技能威力
  结算消耗资源强化(行动者, 技能);

  const 容量 = Math.max(1, Math.floor(技能.攻击容量));
  let 候选: 战斗单位[];
  if (侵蚀) {
    // 侵蚀: 随机攻击场上任意存活单位 (含友方, 不含自身)
    const 池 = 战斗.单位.filter(单位 => 单位 !== 行动者 && 存活(单位));
    候选 = [];
    while (候选.length < 容量 && 池.length > 0) {
      const 下标 = 随机整数(0, 池.length - 1, rng);
      候选.push(池[下标]);
      池.splice(下标, 1);
    }
    if (技能.类别 === 'EGO') 战斗.日志.push(`【侵蚀】${行动者.名称} 的 ${技能.名称} 失控, 将无差别攻击`);
  } else {
    候选 = 行动者.已选目标
      .map(名称 => 战斗.单位.find(单位 => 单位.名称 === 名称))
      .filter((目标): 目标 is 战斗单位 => !!目标 && 存活(目标) && 敌对(行动者, 目标))
      .slice(0, 容量);
    if (候选.length === 0) {
      const 补充 = 战斗.单位.filter(单位 => 敌对(行动者, 单位) && 存活(单位)).slice(0, 容量);
      候选.push(...补充);
    }
  }

  if (候选.length === 0) {
    行动者.已行动 = true;
    行动者.已选技能 = null;
    行动者.已选目标 = [];
    delete 行动者.状态效果[资源强化状态];
    战斗.日志.push(`${行动者.名称} 没有可攻击的目标`);
    return null;
  }

  行动者.已选目标 = 候选.map(目标 => 目标.名称);
  行动者.已行动 = true;

  const 结果列表: 命中结果[] = [];
  for (const 目标 of 候选) {
    if (!存活(目标)) continue;
    if (!侵蚀 && !敌对(行动者, 目标)) continue;
    结果列表.push(解决单目标({ 战斗, 行动者, 技能, 目标, rng, 侵蚀 }));
    if (!存活(行动者)) break;
  }

  delete 行动者.状态效果[资源强化状态];
  行动者.已选技能 = null;
  行动者.已选目标 = [];
  检查结束(战斗);
  return 结果列表;
}

export function 检查结束(战斗: 战斗状态): void {
  const 玩家方存活 = 战斗.单位.some(单位 => 单位.阵营 !== '敌人' && 存活(单位));
  const 敌方存活 = 战斗.单位.some(单位 => 单位.阵营 === '敌人' && 存活(单位));
  if (!敌方存活) 战斗.结束 = '玩家胜';
  else if (!玩家方存活) 战斗.结束 = '敌人胜';
}

/** 推进到下一个行动者; 返回是否进入新回合 */
export function 推进行动(战斗: 战斗状态): boolean {
  if (战斗.结束) return false;
  战斗.行动指针 += 1;
  while (战斗.行动指针 < 战斗.速度顺序.length && !存活(名称查单位(战斗, 战斗.速度顺序[战斗.行动指针]))) {
    战斗.行动指针 += 1;
  }
  if (战斗.行动指针 >= 战斗.速度顺序.length) return true;
  战斗.当前行动者 = 战斗.速度顺序[战斗.行动指针];
  return false;
}

function 名称查单位(战斗: 战斗状态, 名称: string): 战斗单位 {
  return 战斗.单位.find(单位 => 单位.名称 === 名称) ?? 战斗.单位[0];
}

/** 回合结束结算烧伤等, 处理恐慌与混乱退出, 并递增回合数、重排速度 */
export function 结束回合(战斗: 战斗状态, rng: 随机源 = 默认随机源): void {
  for (const 单位 of 战斗.单位) {
    if (!存活(单位)) continue;
    for (const 项 of 回合结束触发(单位)) {
      if (项.类型 === '固定') 单位.生命值 = Math.max(0, 单位.生命值 - 项.数值);
      else 单位.理智值 = Math.max(-45, Math.min(45, 单位.理智值 - 项.数值));
    }
    更新士气低落(单位);
    if (单位.恐慌状态 === '生效中') {
      // 恐慌回合结束: SP 重置为 0 并退出恐慌
      单位.理智值 = 0;
      单位.恐慌状态 = '无';
      更新士气低落(单位);
    } else if (单位.恐慌状态 === '待生效') {
      单位.恐慌状态 = '生效中';
    }
    if (是否混乱(单位)) 单位.混乱值 = 0;
  }
  战斗.回合 += 1;
  战斗.日志.push(`第 ${战斗.回合} 回合开始`);
  检查结束(战斗);
  if (!战斗.结束) 准备回合(战斗, rng);
}

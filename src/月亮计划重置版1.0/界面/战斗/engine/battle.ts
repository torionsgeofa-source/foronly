import type { 技能, 战斗单位, 战斗状态, 命中结果, 伤害明细, 追加伤害记录 } from './types';
import { 正面率, 默认随机源, 掷硬币, 随机整数, type 随机源 } from './rng';
import { 聚合加成, 是否混乱, 回合结束触发, 命中触发 } from './status';
import { 拼点, 构建硬币 } from './clash';
import { 执行命中 } from './damage';

export function 存活(单位: 战斗单位): boolean {
  return 单位.生命值 > 0;
}

export function 有效速度(单位: 战斗单位): number {
  return Math.max(1, 单位.速度 + 聚合加成(单位).速度);
}

export function 敌对(左: 战斗单位, 右: 战斗单位): boolean {
  return (左.阵营 === '敌人') !== (右.阵营 === '敌人');
}

export function 计算速度顺序(单位: 战斗单位[], rng: 随机源 = 默认随机源): string[] {
  return 单位
    .filter(存活)
    .map(单位 => ({ 名称: 单位.名称, 速度: 有效速度(单位), 随机: rng() }))
    .sort((左, 右) => 右.速度 - 左.速度 || 右.随机 - 左.随机)
    .map(项 => 项.名称);
}

export function 创建战斗状态(单位: 战斗单位[], rng: 随机源 = 默认随机源): 战斗状态 {
  const 顺序 = 计算速度顺序(单位, rng);
  return {
    单位,
    回合: 1,
    速度顺序: 顺序,
    当前行动者: 顺序[0] ?? '',
    行动指针: 0,
    日志: ['战斗开始'],
    结束: null,
  };
}

export function 当前单位(战斗: 战斗状态): 战斗单位 | undefined {
  return 战斗.单位.find(单位 => 单位.名称 === 战斗.速度顺序[战斗.行动指针]);
}

function 选择AI技能(单位: 战斗单位, rng: 随机源): 技能 | null {
  const 技能列表 = Object.values(单位.技能);
  if (技能列表.length === 0) return null;
  const 攻击技能 = 技能列表.filter(技能 => 技能.类别 === '攻击');
  const 守备技能 = 技能列表.filter(技能 => 技能.类别 === '守备');
  if (单位.生命值 <= 单位.生命上限 * 0.3 && 守备技能.length > 0 && rng() < 0.35) {
    return 守备技能[随机整数(0, 守备技能.length - 1, rng)];
  }
  const 池 = 攻击技能.length > 0 ? 攻击技能 : 技能列表;
  return 池[随机整数(0, 池.length - 1, rng)];
}

function 选择AI目标(单位: 战斗单位, 全体: 战斗单位[], rng: 随机源): 战斗单位 | null {
  const 敌人列表 = 全体.filter(目标 => 敌对(单位, 目标) && 存活(目标));
  if (敌人列表.length === 0) return null;
  return 敌人列表[随机整数(0, 敌人列表.length - 1, rng)];
}

/** 所有非玩家单位自动选择技能与目标 */
export function 准备回合(战斗: 战斗状态, rng: 随机源 = 默认随机源): void {
  for (const 单位 of 战斗.单位) {
    单位.已选技能 = null;
    单位.已选目标 = null;
    单位.已行动 = false;
  }
  for (const 单位 of 战斗.单位) {
    if (单位.是否玩家 || !存活(单位)) continue;
    const 技能 = 选择AI技能(单位, rng);
    if (!技能) continue;
    单位.已选技能 = 技能.名称;
    const 目标 = 选择AI目标(单位, 战斗.单位, rng);
    单位.已选目标 = 目标 ? 目标.名称 : null;
  }
  战斗.速度顺序 = 计算速度顺序(战斗.单位, rng);
  战斗.行动指针 = 0;
  战斗.当前行动者 = 战斗.速度顺序[0] ?? '';
}

function 掷出攻击硬币(技能: 技能, 单位: 战斗单位, rng: 随机源) {
  const 硬币列表 = 构建硬币(技能);
  const 概率 = 正面率(单位.理智值);
  for (const 硬币 of 硬币列表) {
    硬币.正面 = 掷硬币(概率, rng);
  }
  return 硬币列表;
}

/** 结算当前行动者的行动; 玩家尚未选择技能/目标时返回 null */
export function 结算当前行动(战斗: 战斗状态, rng: 随机源 = 默认随机源): 命中结果 | null {
  const 行动者 = 当前单位(战斗);
  if (!行动者 || !存活(行动者) || 行动者.已行动 || !行动者.已选技能) return null;

  const 技能 = 行动者.技能[行动者.已选技能];
  if (!技能) {
    行动者.已选技能 = null;
    return null;
  }

  let 目标 = 战斗.单位.find(单位 => 单位.名称 === 行动者.已选目标);
  if (!目标 || !存活(目标) || !敌对(行动者, 目标)) {
    目标 = 战斗.单位.find(单位 => 敌对(行动者, 单位) && 存活(单位));
    行动者.已选目标 = 目标 ? 目标.名称 : null;
  }
  if (!目标) {
    战斗.日志.push(`${行动者.名称} 没有可攻击的目标`);
    return null;
  }

  const 目标技能名 = 目标.已选技能;
  const 目标技能 = 目标技能名 ? 目标.技能[目标技能名] : undefined;
  const 目标索引 = 战斗.速度顺序.indexOf(目标.名称);
  const 会拼点 = !!目标技能 && 目标索引 > 战斗.行动指针;

  let 拼点结果 = undefined;
  let 攻击方 = 行动者;
  let 受击方 = 目标;

  if (会拼点 && 目标技能) {
    拼点结果 = 拼点(行动者, 技能, 目标, 目标技能, rng);
    if (拼点结果.胜者 === '右') {
      攻击方 = 目标;
      受击方 = 行动者;
    } else if (拼点结果.胜者 === '无') {
      目标.已选技能 = null;
      目标.已选目标 = null;
      目标.已行动 = true;
      行动者.已行动 = true;
      const 文本 = `${行动者.名称} 与 ${目标.名称} 拼点僵持, 均未受创`;
      战斗.日志.push(文本);
      return 无攻击结果(行动者, 目标, 技能, 拼点结果, 文本);
    }
    // 拼点消耗防守方的技能
    目标.已选技能 = null;
    目标.已选目标 = null;
    目标.已行动 = true;
  }

  const 攻击技能 = 攻击方 === 行动者 ? 技能 : (目标技能 ?? 技能);
  const 硬币列表 = 会拼点 && 拼点结果
    ? (攻击方 === 行动者 ? 拼点结果.左侧剩余硬币 : 拼点结果.右侧剩余硬币)
    : 掷出攻击硬币(攻击技能, 攻击方, rng);

  const 加成 = 聚合加成(攻击方);
  const 拼点回合数 = 拼点结果 ? 拼点结果.记录.length : 0;
  const 伤害列表: 伤害明细[] = [];
  const 全部追加: 追加伤害记录[] = [];

  for (const 硬币 of 硬币列表) {
    if (硬币.已摧毁) continue;
    const 命中 = 硬币.已破碎 || 硬币.正面;
    if (!命中) continue;
    const 基础硬币威力 = (硬币.已破碎 ? 1 : 硬币.威力) + 加成.最终威力;
    const 触发结果 = 命中触发(攻击方, 受击方, rng);
    伤害列表.push(
      执行命中({
        攻击方,
        受击方,
        技能: 攻击技能,
        硬币威力: 基础硬币威力,
        拼点回合数,
        暴击: 触发结果.暴击,
        追加: 触发结果.追加,
      }),
    );
    全部追加.push(...触发结果.追加);
    if (!存活(受击方)) break;
  }

  const 文本 = 生成文本(行动者, 攻击方, 受击方, 攻击技能.名称, 伤害列表, 拼点结果, 受击方.生命值 <= 0);
  战斗.日志.push(文本);
  行动者.已行动 = true;
  检查结束(战斗);

  return {
    来源: 攻击方.名称,
    目标: 受击方.名称,
    技能: 攻击技能.名称,
    拼点: 拼点结果,
    伤害: 伤害列表,
    追加: 全部追加,
    文本,
    目标死亡: 受击方.生命值 <= 0,
    目标混乱: 是否混乱(受击方),
  };
}

function 无攻击结果(
  行动者: 战斗单位,
  目标: 战斗单位,
  技能: 技能,
  拼点结果: ReturnType<typeof 拼点>,
  文本: string,
): 命中结果 {
  return {
    来源: 行动者.名称,
    目标: 目标.名称,
    技能: 技能.名称,
    拼点: 拼点结果,
    伤害: [],
    追加: [],
    文本,
    目标死亡: 目标.生命值 <= 0,
    目标混乱: 是否混乱(目标),
  };
}

function 生成文本(
  行动者: 战斗单位,
  攻击方: 战斗单位,
  受击方: 战斗单位,
  技能名: string,
  伤害列表: 伤害明细[],
  拼点结果: ReturnType<typeof 拼点> | undefined,
  死亡: boolean,
): string {
  const 拼点描述 = 拼点结果
    ? `拼点 ${拼点结果.记录.length} 回合(${拼点结果.胜者 === '左' ? 行动者.名称 : 拼点结果.胜者 === '右' ? 拼点结果.右侧名称 : '无果'}) `
    : '';
  const 总伤害 = 伤害列表.reduce((和, 项) => 和 + 项.数值, 0);
  const 暴击 = 伤害列表.some(项 => 项.暴击) ? '暴击! ' : '';
  const 死亡描述 = 死亡 ? `, ${受击方.名称} 倒下` : '';
  return `${攻击方.名称} 以 ${技能名} ${拼点描述}对 ${受击方.名称} 造成 ${总伤害} 伤害${暴击 ? ` (${暴击.trim()})` : ''}${死亡描述}`;
}

export function 检查结束(战斗: 战斗状态): void {
  const 玩家方存活 = 战斗.单位.some(单位 => 单位.阵营 !== '敌人' && 存活(单位));
  const 敌方存活 = 战斗.单位.some(单位 => 单位.阵营 === '敌人' && 存活(单位));
  if (!敌方存活) 战斗.结束 = '玩家胜';
  else if (!玩家方存活) 战斗.结束 = '敌人胜';
}

/** 推进到下一个行动者; 返回是否进入新回合 */
export function 推进行动(战斗: 战斗状态): boolean {
  if (战斗.结束) return false;
  战斗.行动指针 += 1;
  while (战斗.行动指针 < 战斗.速度顺序.length && !存活(名称查单位(战斗, 战斗.速度顺序[战斗.行动指针]))) {
    战斗.行动指针 += 1;
  }
  if (战斗.行动指针 >= 战斗.速度顺序.length) return true;
  战斗.当前行动者 = 战斗.速度顺序[战斗.行动指针];
  return false;
}

function 名称查单位(战斗: 战斗状态, 名称: string): 战斗单位 {
  return 战斗.单位.find(单位 => 单位.名称 === 名称) ?? 战斗.单位[0];
}

/** 回合结束结算烧伤等, 并递增回合数, 重排速度 */
export function 结束回合(战斗: 战斗状态, rng: 随机源 = 默认随机源): void {
  for (const 单位 of 战斗.单位) {
    if (!存活(单位)) continue;
    for (const 项 of 回合结束触发(单位)) {
      if (项.类型 === '固定') 单位.生命值 = Math.max(0, 单位.生命值 - 项.数值);
      else 单位.理智值 = Math.max(-45, Math.min(45, 单位.理智值 - 项.数值));
    }
    if (是否混乱(单位)) 单位.混乱值 = 0;
  }
  战斗.回合 += 1;
  战斗.日志.push(`第 ${战斗.回合} 回合开始`);
  检查结束(战斗);
  if (!战斗.结束) 准备回合(战斗, rng);
}

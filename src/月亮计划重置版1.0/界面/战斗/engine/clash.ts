import type { 技能, 硬币, 战斗单位, 拼点结果, 拼点回合记录, 拼点硬币记录 } from './types';
import { 正面率, 掷硬币, 默认随机源, type 随机源 } from './rng';
import { 聚合加成, 掷币触发 } from './status';

const 最大拼点次数 = 99;

export function 构建硬币(技能: 技能): 硬币[] {
  return 技能.硬币威力.map((威力, 下标) => ({
    id: 下标 + 1,
    威力,
    类型: 技能.硬币类型[下标] ?? '普通',
    正面: false,
    已摧毁: false,
    已破碎: false,
  }));
}

function 存活硬币(硬币: 硬币[]): 硬币[] {
  return 硬币.filter(硬币 => !硬币.已摧毁);
}

function 有截除(硬币: 硬币[]): boolean {
  return 存活硬币(硬币).some(硬币 => 硬币.类型 === '截除');
}

function 有无我(硬币: 硬币[]): boolean {
  return 存活硬币(硬币).some(硬币 => 硬币.类型 === '无我');
}

interface 掷币结果 {
  记录: 拼点硬币记录[];
  威力: number;
}

function 一侧掷币(
  硬币列表: 硬币[],
  技能: 技能,
  单位: 战斗单位,
  拼点加成: number,
  攻击等级加成: number,
  麻痹: number,
  rng: 随机源,
): 掷币结果 {
  const 概率 = 正面率(单位.理智值);
  const 记录: 拼点硬币记录[] = [];
  let 合计 = 技能.基础威力 + 拼点加成 + 攻击等级加成;

  for (const 硬币 of 存活硬币(硬币列表)) {
    if (硬币.已破碎) {
      硬币.正面 = false;
      记录.push({ id: 硬币.id, 威力: 硬币.威力, 类型: 硬币.类型, 正面: false, 固定: true });
      合计 += 1;
      continue;
    }
    const 正面 = 掷硬币(概率, rng);
    硬币.正面 = 正面;
    const 威力 = 硬币.id <= 麻痹 ? 0 : 硬币.威力;
    记录.push({ id: 硬币.id, 威力, 类型: 硬币.类型, 正面, 固定: false });
    if (正面) 合计 += 威力;
  }

  return { 记录, 威力: 合计 };
}

function 攻击等级加成(攻击方: 战斗单位, 防御方: 战斗单位): number {
  const 攻 = 攻击方.攻击等级 + 聚合加成(攻击方).攻击等级;
  const 防 = 防御方.攻击等级 + 聚合加成(防御方).攻击等级;
  const 差 = 攻 - 防;
  return 差 > 0 ? Math.floor(差 / 3) : 0;
}

interface 摧毁结果 {
  硬币id: number;
  类型: '摧毁' | '破碎' | '无';
}

/** 拼点失败时的摧毁: 优先摧毁普通硬币; 若只剩不可摧毁硬币则将其转为破碎(威力固定 1) */
function 摧毁普通(硬币列表: 硬币[]): 摧毁结果 {
  const 普通 = 存活硬币(硬币列表).find(硬币 => 硬币.类型 === '普通');
  if (普通) {
    普通.已摧毁 = true;
    return { 硬币id: 普通.id, 类型: '摧毁' };
  }
  const 红 = 存活硬币(硬币列表).find(硬币 => 硬币.类型 !== '普通' && !硬币.已破碎);
  if (红) {
    红.已破碎 = true;
    return { 硬币id: 红.id, 类型: '破碎' };
  }
  return { 硬币id: -1, 类型: '无' };
}

function 摧毁红币(硬币列表: 硬币[]): 摧毁结果 {
  const 红 = 存活硬币(硬币列表).find(硬币 => 硬币.类型 !== '普通');
  if (红) {
    红.已摧毁 = true;
    return { 硬币id: 红.id, 类型: '摧毁' };
  }
  return { 硬币id: -1, 类型: '无' };
}

function 摧毁任意(硬币列表: 硬币[]): 摧毁结果 {
  const 目标 = 存活硬币(硬币列表).find(硬币 => 硬币.类型 === '普通') ?? 存活硬币(硬币列表)[0];
  if (目标) {
    目标.已摧毁 = true;
    return { 硬币id: 目标.id, 类型: '摧毁' };
  }
  return { 硬币id: -1, 类型: '无' };
}

function 快照(硬币列表: 硬币[]): 硬币[] {
  return 硬币列表.map(硬币 => ({ ...硬币 }));
}

/** 双方拼点, 返回完整过程与残余硬币 (残余硬币用于后续攻击) */
export function 拼点(左侧: 战斗单位, 左侧技能: 技能, 右侧: 战斗单位, 右侧技能: 技能, rng: 随机源 = 默认随机源): 拼点结果 {
  const 左硬币 = 构建硬币(左侧技能);
  const 右硬币 = 构建硬币(右侧技能);
  const 左侧初始硬币 = 快照(左硬币);
  const 右侧初始硬币 = 快照(右硬币);

  const 左加成 = 聚合加成(左侧);
  const 右加成 = 聚合加成(右侧);
  const 左攻级加成 = 攻击等级加成(左侧, 右侧);
  const 右攻级加成 = 攻击等级加成(右侧, 左侧);

  const 记录: 拼点回合记录[] = [];
  let 胜者: '左' | '右' | '无' = '无';

  for (let 回合数 = 1; 回合数 <= 最大拼点次数; 回合数++) {
    const 左活 = 存活硬币(左硬币).length > 0;
    const 右活 = 存活硬币(右硬币).length > 0;
    if (!左活 || !右活) break;

    if (回合数 === 1) {
      for (const 项 of 掷币触发(左侧)) if (项.类型 === '固定') 左侧.生命值 = Math.max(0, 左侧.生命值 - 项.数值);
      for (const 项 of 掷币触发(右侧)) if (项.类型 === '固定') 右侧.生命值 = Math.max(0, 右侧.生命值 - 项.数值);
      if (左侧.生命值 <= 0 || 右侧.生命值 <= 0) break;
    }

    const 左掷 = 一侧掷币(左硬币, 左侧技能, 左侧, 左加成.拼点威力, 左攻级加成, 左加成.麻痹, rng);
    const 右掷 = 一侧掷币(右硬币, 右侧技能, 右侧, 右加成.拼点威力, 右攻级加成, 右加成.麻痹, rng);

    let 结果: '左胜' | '右胜' | '平局' = '平局';
    let 摧毁: { 方: '左' | '右'; 硬币id: number } | null = null;
    let 额外击碎: { 方: '左' | '右'; 硬币id: number } | null = null;

    if (左掷.威力 > 右掷.威力) {
      结果 = '左胜';
      胜者 = '左';
      const 摧毁结果 = 摧毁普通(右硬币);
      if (摧毁结果.硬币id > 0) 摧毁 = { 方: '右', 硬币id: 摧毁结果.硬币id };
      if (有截除(左硬币)) {
        const 额外 = 摧毁红币(右硬币);
        if (额外.硬币id > 0) 额外击碎 = { 方: '右', 硬币id: 额外.硬币id };
      } else if (有无我(左硬币)) {
        const 额外 = 摧毁任意(右硬币);
        if (额外.硬币id > 0) 额外击碎 = { 方: '右', 硬币id: 额外.硬币id };
      }
    } else if (右掷.威力 > 左掷.威力) {
      结果 = '右胜';
      胜者 = '右';
      const 摧毁结果 = 摧毁普通(左硬币);
      if (摧毁结果.硬币id > 0) 摧毁 = { 方: '左', 硬币id: 摧毁结果.硬币id };
      if (有截除(右硬币)) {
        const 额外 = 摧毁红币(左硬币);
        if (额外.硬币id > 0) 额外击碎 = { 方: '左', 硬币id: 额外.硬币id };
      } else if (有无我(右硬币)) {
        const 额外 = 摧毁任意(左硬币);
        if (额外.硬币id > 0) 额外击碎 = { 方: '左', 硬币id: 额外.硬币id };
      }
    }

    记录.push({
      回合数,
      左侧威力: 左掷.威力,
      右侧威力: 右掷.威力,
      左侧硬币: 左掷.记录,
      右侧硬币: 右掷.记录,
      结果,
      摧毁,
      额外击碎,
    });
  }

  const 左剩 = 存活硬币(左硬币);
  const 右剩 = 存活硬币(右硬币);
  if (左剩.length > 0 && 右剩.length === 0) 胜者 = '左';
  else if (右剩.length > 0 && 左剩.length === 0) 胜者 = '右';
  else if (左剩.length > 0 && 右剩.length > 0) {
    const 末 = 记录[记录.length - 1];
    胜者 = 末 ? (末.结果 === '左胜' ? '左' : 末.结果 === '右胜' ? '右' : '无') : '无';
  }

  return {
    左侧名称: 左侧.名称,
    右侧名称: 右侧.名称,
    左侧技能: 左侧技能.名称,
    右侧技能: 右侧技能.名称,
    胜者,
    记录,
    左侧初始硬币,
    右侧初始硬币,
    左侧剩余硬币: 快照(左硬币),
    右侧剩余硬币: 快照(右硬币),
    左侧攻击等级加成: 左攻级加成,
    右侧攻击等级加成: 右攻级加成,
    左侧拼点威力加成: 左加成.拼点威力,
    右侧拼点威力加成: 右加成.拼点威力,
  };
}

/** 从拼点结果中取出某一方仍存活且未破碎的硬币 (用于发动攻击) */
export function 可攻击硬币(硬币列表: 硬币[]): 硬币[] {
  return 硬币列表.filter(硬币 => !硬币.已摧毁);
}

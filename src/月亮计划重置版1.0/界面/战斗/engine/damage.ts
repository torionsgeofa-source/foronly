import type { 技能, 战斗单位, 追加伤害记录, 伤害明细 } from './types';
import { 夹取 } from './rng';
import { 聚合加成, 施加技能附带状态 } from './status';

/** 单条抗性倍率对应的静态修正 */
export function 抗性修正(倍率: number): number {
  if (倍率 <= 0) return -0.5;
  if (倍率 >= 1) return 倍率 - 1;
  return (倍率 - 1) / 2;
}

export function 攻防等级修正(攻击等级: number, 防御等级: number): number {
  const 差 = 攻击等级 - 防御等级;
  return 差 / (Math.abs(差) + 25);
}

export function 混乱档位(单位: 战斗单位): number {
  if (!(单位.混乱阈值 > 0 && 单位.混乱值 >= 单位.混乱阈值)) return 0;
  return 单位.混乱值 >= 单位.混乱阈值 * 2 ? 2 : 1;
}

export function 应用追加伤害(单位: 战斗单位, 追加: 追加伤害记录[]): void {
  for (const 项 of 追加) {
    if (项.类型 === '理智') {
      单位.理智值 = 夹取(单位.理智值 - 项.数值, -45, 45);
    } else {
      单位.生命值 = Math.max(0, 单位.生命值 - 项.数值);
    }
  }
}

export interface 伤害输入 {
  攻击方: 战斗单位;
  受击方: 战斗单位;
  技能: 技能;
  硬币威力: number;
  拼点回合数: number;
  暴击: boolean;
  追加: 追加伤害记录[];
}

export function 计算伤害(输入: 伤害输入): 伤害明细 {
  const { 攻击方, 受击方, 技能 } = 输入;
  const 攻击加成 = 聚合加成(攻击方);
  const 受击加成 = 聚合加成(受击方);

  const 罪孽修正 = 抗性修正(受击方.罪孽抗性[技能.罪孽] ?? 1);
  const 物理修正 = (() => {
    const 档位 = 混乱档位(受击方);
    if (档位 > 0) return 档位 * 0.5 + 0.5;
    return 抗性修正(受击方.物理抗性[技能.攻击类型] ?? 1);
  })();

  const 攻击等级 = 攻击方.攻击等级 + 攻击加成.攻击等级;
  const 防御等级 = 受击方.防御等级 + 受击加成.防御等级;
  const 等级修正 = 攻防等级修正(攻击等级, 防御等级);
  const 暴击修正 = 输入.暴击 ? 0.2 + 攻击加成.暴击伤害 : 0;
  const 拼点修正 = 输入.拼点回合数 * 0.03;

  const 静态 = 罪孽修正 + 物理修正 + 等级修正 + 暴击修正 + 拼点修正;
  const 动态 = 夹取(攻击加成.造成伤害 + 受击加成.受到伤害, -1, 2);

  const 硬币威力 = 输入.硬币威力;
  let 数值 = Math.floor(硬币威力 * (1 + 静态) * (1 + 动态));
  数值 = Math.max(1, 数值);
  数值 = Math.max(数值, Math.floor(Math.max(0, 硬币威力) * 0.05));

  return {
    目标: 受击方.名称,
    数值,
    暴击: 输入.暴击,
    罪孽: 技能.罪孽,
    攻击类型: 技能.攻击类型,
    静态,
    动态,
    追加: [...输入.追加],
  };
}

/** 将伤害与追加伤害应用到受击方 */
export function 执行命中(输入: 伤害输入): 伤害明细 {
  const 明细 = 计算伤害(输入);
  输入.受击方.生命值 = Math.max(0, 输入.受击方.生命值 - 明细.数值);
  输入.受击方.混乱值 += 明细.数值;
  应用追加伤害(输入.受击方, 输入.追加);
  施加技能附带状态(输入.攻击方, 输入.受击方, 输入.技能.效果);
  return 明细;
}

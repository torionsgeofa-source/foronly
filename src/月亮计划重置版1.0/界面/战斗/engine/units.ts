function 推断守备(名称: string, 效果: string): { 类别: '攻击' | '守备'; 守备类型?: 守备类型名 } {
  const 文本 = `${名称} ${效果}`;
  const 规则: Array<[string, 守备类型名]> = [
    ['强化反击', '强化反击'],
    ['强化防御', '强化防御'],
    ['反击', '反击'],
    ['闪避', '闪避'],
    ['格挡', '防御'],
    ['招架', '防御'],
    ['防御', '防御'],
  ];
  for (const [关键词, 类型] of 规则) {
    if (文本.includes(关键词)) return { 类别: '守备', 守备类型: 类型 };
  }
  return { 类别: '攻击' };
}

/**
 * 将 MVU 技能记录转换为引擎技能; 若内置技能库存在同名技能, 则优先补全硬币类型等字段.
 */
export function 技能记录转技能(
  记录: Record<
    string,
    {
      罪孽?: string;
      攻击类型?: string;
      基础威力?: number;
      硬币威力?: number[];
      攻击等级修正?: number;
      攻击容量?: number;
      效果?: string;
      类别?: string;
      守备类型?: string;
      资源消耗?: number;
      SP消耗?: number;
    }
  >,
): Record<string, 技能> {
  const 结果: Record<string, 技能> = {};
  for (const [名称, 原始] of Object.entries(记录)) {
    const 硬币威力 = Array.isArray(原始.硬币威力) && 原始.硬币威力.length > 0 ? 原始.硬币威力 : [0];
    const 内置 = 内置技能库[名称];
    const 原始类别 = 原始.类别 === '攻击' || 原始.类别 === '守备' || 原始.类别 === 'EGO' ? 原始.类别 : undefined;
    const 推断 = 内置 ? { 类别: 内置.类别, 守备类型: 内置.守备类型 } : 推断守备(名称, 原始.效果 ?? '');
    // 内置同名技能以库中定义为准 (避免 schema 对 类别 的 prefault '攻击' 覆盖守备/EGO)
    const 类别 = 内置 ? 内置.类别 : (原始类别 ?? 推断.类别);
    const 原始守备 = 原始.守备类型 as 守备类型名 | undefined;
    const 守备类型 = 类别 === '守备' ? (内置?.守备类型 || 原始守备 || 推断.守备类型) : undefined;
    const 资源消耗 = 类别 === 'EGO' ? (Number(原始.资源消耗) || 内置?.资源消耗 || 3) : (Number(原始.资源消耗) || 0);
    const SP消耗 = 类别 === 'EGO' ? (Number(原始.SP消耗) || 内置?.SP消耗 || 10) : (Number(原始.SP消耗) || 0);
    const 基础: 技能 = {
      名称,
      罪孽: ((原始.罪孽 ?? 内置?.罪孽 ?? '暴怒') as 罪孽名),
      攻击类型: ((原始.攻击类型 ?? 内置?.攻击类型 ?? '打击') as 攻击类型名),
      基础威力: Number(原始.基础威力 ?? 内置?.基础威力 ?? 0),
      硬币威力: [...硬币威力],
      硬币类型: 内置 && 内置.硬币类型.length === 硬币威力.length ? [...内置.硬币类型] : 硬币威力.map(() => '普通' as 硬币类型),
      攻击等级修正: Number(原始.攻击等级修正 ?? 内置?.攻击等级修正 ?? 0),
      攻击容量: Math.max(1, Number(原始.攻击容量 ?? 内置?.攻击容量 ?? 1)),
      效果: 原始.效果 ?? 内置?.效果 ?? '',
      类别,
      守备类型,
      资源消耗,
      SP消耗,
      effects: 内置?.effects ? 内置.effects.map(效果 => ({ ...效果 })) : undefined,
    };
    结果[名称] = 基础;
  }
  return 结果;
}

/** 根据身份找一个模板, 找不到则用收尾人模板兜底 */
export function 查找模板(身份: string): 单位模板 {
  return 敌人库[身份] ?? 身份库[身份] ?? 身份库.收尾人;
}

/** 为缺少技能的 AI 单位补齐该身份的默认技能 */
export function 补齐技能(单位: 战斗单位): 战斗单位 {
  if (Object.keys(单位.技能).length > 0) return 单位;
  const 模板 = 查找模板(单位.身份);
  const 技能表: Record<string, 技能> = {};
  for (const 技能名 of 模板.技能) {
    const 技能 = 内置技能库[技能名];
    if (技能) 技能表[技能名] = 复制技能(技能);
  }
  单位.技能 = 技能表;
  return 单位;
}

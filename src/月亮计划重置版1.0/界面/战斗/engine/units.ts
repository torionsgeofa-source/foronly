export function 构造技能(数据: {
  名称: string;
  基础威力: number;
  硬币威力: number[];
  罪孽?: 罪孽名;
  攻击类型?: 攻击类型名;
  硬币类型?: 硬币类型[];
  攻击等级修正?: number;
  攻击容量?: number;
  效果?: string;
  类别?: '攻击' | '守备';
}): 技能 {
  return {
    名称: 数据.名称,
    罪孽: 数据.罪孽 ?? '暴怒',
    攻击类型: 数据.攻击类型 ?? '打击',
    基础威力: 数据.基础威力,
    硬币威力: [...数据.硬币威力],
    硬币类型: 数据.硬币类型 ? [...数据.硬币类型] : 数据.硬币威力.map(() => '普通' as 硬币类型),
    攻击等级修正: 数据.攻击等级修正 ?? 0,
    攻击容量: 数据.攻击容量 ?? 1,
    效果: 数据.效果 ?? '',
    类别: 数据.类别 ?? '攻击',
  };
}


import type { 技能, 战斗单位, 罪孽名, 攻击类型名, 硬币类型, 阵营名, 守备类型名, 速度区间, 技能类别, 技能效果 } from './types';

export function 构造技能(数据: {
  名称: string;
  基础威力: number;
  硬币威力: number[];
  罪孽?: 罪孽名;
  攻击类型?: 攻击类型名;
  硬币类型?: 硬币类型[];
  攻击等级修正?: number;
  攻击容量?: number;
  效果?: string;
  类别?: 技能类别;
  守备类型?: 守备类型名;
  资源消耗?: number;
  SP消耗?: number;
  effects?: 技能效果[];
}): 技能 {
  const 类别 = 数据.类别 ?? '攻击';
  return {
    名称: 数据.名称,
    罪孽: 数据.罪孽 ?? '暴怒',
    攻击类型: 数据.攻击类型 ?? '打击',
    基础威力: 数据.基础威力,
    硬币威力: [...数据.硬币威力],
    硬币类型: 数据.硬币类型 ? [...数据.硬币类型] : 数据.硬币威力.map(() => '普通' as 硬币类型),
    攻击等级修正: 数据.攻击等级修正 ?? 0,
    攻击容量: 数据.攻击容量 ?? 1,
    效果: 数据.效果 ?? '',
    类别,
    守备类型: 数据.守备类型,
    资源消耗: 数据.资源消耗 ?? (类别 === 'EGO' ? 3 : 0),
    SP消耗: 数据.SP消耗 ?? (类别 === 'EGO' ? 10 : 0),
    effects: 数据.effects ? 数据.effects.map(效果 => ({ ...效果 })) : undefined,
  };
}


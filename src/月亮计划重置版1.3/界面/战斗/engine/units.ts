function 推断守备(名称: string, 效果: string): { 类别: '战斗' | '守备'; 守备类型?: 守备类型名 } {
  const 文本 = `${名称} ${效果}`;
  const 规则: Array<[string, 守备类型名]> = [
    ['强化反击', '强化反击'],
    ['强化防御', '强化防御'],
    ['反击', '反击'],
    ['闪避', '闪避'],
    ['格挡', '防御'],
    ['招架', '防御'],
    ['防御', '防御'],
  ];
  for (const [关键词, 类型] of 规则) {
    if (文本.includes(关键词)) return { 类别: '守备', 守备类型: 类型 };
  }
  return { 类别: '战斗' };
}


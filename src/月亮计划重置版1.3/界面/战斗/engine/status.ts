import type { 追加伤害记录, 战斗单位, 技能, 技能效果, 罪孽名, 数值调整 } from './types';
import { 罪孽列表 } from './types';
import { 夹取, 默认随机源, 掷硬币, type 随机源 } from './rng';

export const 层数上限表: Record<string, number> = {
  攻击等级提升: 10,
  攻击等级降低: 10,
  防御等级提升: 10,
  防御等级降低: 10,
  伤害强化: 10,
  守护: 10,
  忍耐: 10,
  易损: 10,
  伤害弱化: 10,
  充能: 20,
};

/** 攻击方自身获得的增益状态 (结构化效果默认作用于受击方, 这些除外) */
const 自我增益列表 = ['充能', '呼吸法', '强壮', '守护', '忍耐', '攻击等级提升', '防御等级提升', '伤害强化', '迅捷', '暴击伤害强化', '威力提升'];

/** 罪孽共鸣临时状态名 */
export const 共鸣攻击状态 = '罪孽共鸣·攻';
export const 共鸣防御状态 = '罪孽共鸣·防';

export function 读取(单位: 战斗单位, 名称: string): number {
  return 单位.状态效果[名称]?.层数 ?? 0;
}

export function 读取强度(单位: 战斗单位, 名称: string): number {
  return 单位.状态效果[名称]?.强度 ?? 0;
}

export function 增加状态(单位: 战斗单位, 名称: string, 强度 = 0, 层数 = 1): void {
  const 当前 = 单位.状态效果[名称] ?? { 强度: 0, 层数: 0 };
  const 上限 = 层数上限表[名称];
  const 新层数 = 当前.层数 + 层数;
  单位.状态效果[名称] = {
    强度: 夹取(当前.强度 + 强度, 0, 999),
    层数: 上限 !== undefined ? 夹取(新层数, 0, 上限) : Math.max(0, 新层数),
  };
  if (单位.状态效果[名称].强度 <= 0 && 单位.状态效果[名称].层数 <= 0) delete 单位.状态效果[名称];
}

export function 按强度增加(单位: 战斗单位, 名称: string, 强度: number, 层数: number): void {
  const 当前 = 单位.状态效果[名称] ?? { 强度: 0, 层数: 0 };
  const 上限 = 层数上限表[名称];
  单位.状态效果[名称] = {
    强度: Math.max(0, 当前.强度 + 强度),
    层数: 上限 !== undefined ? 夹取(当前.层数 + 层数, 0, 上限) : Math.max(0, 当前.层数 + 层数),
  };
}

export function 消耗层数(单位: 战斗单位, 名称: string, 数量 = 1): void {
  const 当前 = 单位.状态效果[名称];
  if (!当前) return;
  当前.层数 -= 数量;
  if (当前.层数 <= 0 && 当前.强度 <= 0) delete 单位.状态效果[名称];
}

/**
 * 罪孽共鸣: 统计我方存活单位本回合所选技能的罪孽, 同一罪孽 >= 2 次时,
 * 参与单位获得 +floor(次数/2) 的攻击等级与防御等级 (本回合有效的临时状态)。
 * 每次调用先清除旧的共鸣加成, 因此可重复调用而不会叠加。
 */
export function 结算罪孽共鸣(全体: 战斗单位[]): string[] {
  for (const 单位 of 全体) {
    delete 单位.状态效果[共鸣攻击状态];
    delete 单位.状态效果[共鸣防御状态];
  }
  const 我方 = 全体.filter(单位 => 单位.阵营 !== '敌人' && 单位.生命值 > 0 && 单位.已选技能);
  const 计数: Record<string, number> = {};
  for (const 单位 of 我方) {
    const 技能 = 单位.已选技能 ? 单位.技能[单位.已选技能] : undefined;
    if (!技能) continue;
    计数[技能.罪孽] = (计数[技能.罪孽] ?? 0) + 1;
  }
  const 日志: string[] = [];
  for (const 罪孽 of 罪孽列表) {
    const 次数 = 计数[罪孽] ?? 0;
    if (次数 < 2) continue;
    const 加成 = Math.floor(次数 / 2);
    日志.push(`罪孽共鸣·${罪孽} ×${次数} (攻防等级 +${加成})`);
    for (const 单位 of 我方) {
      const 技能 = 单位.已选技能 ? 单位.技能[单位.已选技能] : undefined;
      if (!技能 || 技能.罪孽 !== 罪孽) continue;
      增加状态(单位, 共鸣攻击状态, 0, 加成);
      增加状态(单位, 共鸣防御状态, 0, 加成);
    }
  }
  return 日志;
}

export interface 聚合加成 {
  拼点威力: number;
  最终威力: number;
  造成伤害: number;
  受到伤害: number;
  攻击等级: number;
  防御等级: number;
  速度: number;
  暴击伤害: number;
  麻痹: number;
}

export function 聚合加成(单位: 战斗单位): 聚合加成 {
  const 攻级 = 夹取(读取(单位, '攻击等级提升') - 读取(单位, '攻击等级降低'), -10, 10);
  const 防级 = 夹取(读取(单位, '防御等级提升') - 读取(单位, '防御等级降低'), -10, 10);
  return {
    拼点威力: 读取(单位, '拼点威力提升') - 读取(单位, '拼点威力降低'),
    最终威力: 读取(单位, '强壮') + 读取(单位, '威力提升') - 读取(单位, '虚弱') - 读取(单位, '威力降低'),
    造成伤害: 夹取((读取(单位, '伤害强化') - 读取(单位, '伤害弱化')) * 0.1, -1, 1),
    受到伤害: 夹取((读取(单位, '易损') - 读取(单位, '守护') - 读取(单位, '忍耐')) * 0.1, -1, 1),
    攻击等级: 攻级 + 读取(单位, 共鸣攻击状态),
    防御等级: 防级 + 读取(单位, 共鸣防御状态),
    速度: 读取(单位, '迅捷') - 读取(单位, '束缚'),
    暴击伤害: 读取(单位, '暴击伤害强化') * 0.1,
    麻痹: 读取(单位, '麻痹'),
  };
}

export interface 命中触发结果 {
  追加: 追加伤害记录[];
  暴击: boolean;
}

/** 攻击命中受击方时: 结算破裂 / 沉沦, 并按呼吸法判定暴击 */
export function 命中触发(攻击方: 战斗单位, 受击方: 战斗单位, rng: 随机源 = 默认随机源): 命中触发结果 {
  const 追加: 追加伤害记录[] = [];
  let 暴击 = false;

  const 呼吸 = 读取(攻击方, '呼吸法');
  if (呼吸 > 0) {
    const 概率 = 夹取((呼吸 * 5) / 100, 0, 0.95);
    if (掷硬币(概率, rng)) {
      暴击 = true;
      消耗层数(攻击方, '呼吸法', 1);
    }
  }

  const 破裂 = 读取(受击方, '破裂');
  if (破裂 > 0) {
    追加.push({ 名称: '破裂', 数值: 破裂, 类型: '固定' });
    消耗层数(受击方, '破裂', 1);
  }

  const 沉沦 = 读取(受击方, '沉沦');
  if (沉沦 > 0) {
    追加.push({ 名称: '沉沦', 数值: 沉沦, 类型: '理智' });
    消耗层数(受击方, '沉沦', 1);
  }

  return { 追加, 暴击 };
}

/** 掷出一枚攻击硬币时: 结算流血 */
export function 掷币触发(单位: 战斗单位): 追加伤害记录[] {
  const 流血 = 读取(单位, '流血');
  if (流血 > 0) {
    消耗层数(单位, '流血', 1);
    return [{ 名称: '流血', 数值: 流血, 类型: '固定' }];
  }
  return [];
}

/** 回合结束时: 结算烧伤 (固定伤害), 递减震颤 / 呼吸法 / 充能 */
export function 回合结束触发(单位: 战斗单位): 追加伤害记录[] {
  const 追加: 追加伤害记录[] = [];
  const 烧伤 = 读取(单位, '烧伤');
  if (烧伤 > 0) {
    追加.push({ 名称: '烧伤', 数值: 烧伤, 类型: '固定' });
    消耗层数(单位, '烧伤', 1);
  }
  if (读取(单位, '震颤') > 0) 消耗层数(单位, '震颤', 1);
  if (读取(单位, '呼吸法') > 0) 消耗层数(单位, '呼吸法', 1);
  if (读取(单位, '充能') > 0) 消耗层数(单位, '充能', 1);
  // 「忍耐」与罪孽共鸣仅在本回合生效
  if (单位.状态效果.忍耐) delete 单位.状态效果.忍耐;
  delete 单位.状态效果[共鸣攻击状态];
  delete 单位.状态效果[共鸣防御状态];
  return 追加;
}

export function 是否混乱(单位: 战斗单位): boolean {
  return 单位.混乱阈值 > 0 && 单位.混乱值 >= 单位.混乱阈值;
}

/** SP 统一夹取到 [-45, 45], 并在触底时进入恐慌流程 */
export function 调整SP(单位: 战斗单位, 变化: number): number {
  const 旧值 = 单位.理智值;
  单位.理智值 = 夹取(单位.理智值 + 变化, -45, 45);
  if (单位.理智值 <= -45 && 单位.恐慌状态 === '无') 单位.恐慌状态 = '待生效';
  更新士气低落(单位);
  return 单位.理智值 - 旧值;
}

/** SP < -20 时标记「士气低落」供 UI 展示, 不额外改数值 */
export function 更新士气低落(单位: 战斗单位): void {
  if (单位.理智值 < -20) {
    单位.状态效果.士气低落 = { 强度: 0, 层数: 1 };
  } else if (单位.状态效果.士气低落) {
    delete 单位.状态效果.士气低落;
  }
}

/** 施加状态时的落点选择: 来源 / 目标 / 自动 (增益落来源, 减益落目标, 兼容旧战斗逻辑) */
export type 状态目标选项 = '来源' | '目标' | '自动';

function 解析状态目标(来源: 战斗单位, 目标: 战斗单位, 状态: string, 指定: 状态目标选项): 战斗单位 {
  if (指定 === '来源') return 来源;
  if (指定 === '目标') return 目标;
  return 自我增益列表.includes(状态) ? 来源 : 目标;
}

/** 将数值调整直接写入单位字段并夹取范围 */
function 应用数值调整(目标: 战斗单位, 数值: 数值调整): void {
  if (数值.生命 !== undefined) 目标.生命值 = 夹取(目标.生命值 + 数值.生命, 0, Math.max(1, 目标.生命上限));
  if (数值.SP !== undefined) 调整SP(目标, 数值.SP);
  if (数值.攻击等级 !== undefined) 目标.攻击等级 = Math.max(1, Math.round(目标.攻击等级 + 数值.攻击等级));
  if (数值.防御等级 !== undefined) 目标.防御等级 = Math.max(1, Math.round(目标.防御等级 + 数值.防御等级));
}

/** 结算单条结构化技能效果 */
function 结算单条效果(来源: 战斗单位, 目标: 战斗单位, 效果: 技能效果, 状态目标: 状态目标选项 = '自动'): void {
  switch (效果.type) {
    case '施加状态': {
      const 落点 = 解析状态目标(来源, 目标, 效果.状态, 状态目标);
      增加状态(落点, 效果.状态, 效果.强度 ?? 0, 效果.层数 ?? 1);
      break;
    }
    case '调整数值': {
      应用数值调整(目标, 效果.数值);
      break;
    }
    case '震颤引爆': {
      if (读取(目标, '震颤') > 0) {
        const 强度 = 读取强度(目标, '震颤');
        if (强度 > 0) 目标.混乱阈值 = Math.max(1, 目标.混乱阈值 - 强度);
        消耗层数(目标, '震颤', 1);
      }
      break;
    }
    case '获得护盾': {
      目标.护盾 = Math.max(0, (目标.护盾 ?? 0) + 效果.数值);
      break;
    }
    // 条件增伤不是主动施加效果, 其数值在 damage.ts 的 计算伤害() 中按条件累计
  }
}

/**
 * 统一执行函数: 对 目标 结算 效果列表。
 * 状态目标默认 '自动' (增益落来源/减益落目标), 被动与支援传 '目标' 使效果落在受益单位上。
 */
export function 执行效果(来源: 战斗单位, 目标: 战斗单位, 效果列表: 技能效果[], 状态目标: 状态目标选项 = '自动'): void {
  for (const 效果 of 效果列表) 结算单条效果(来源, 目标, 效果, 状态目标);
}

function 符号数(值: number): string {
  return `${值 >= 0 ? '+' : ''}${值}`;
}

/** 将单条技能效果转为中文短句, 供 UI tooltip / 日志使用 */
export function 描述效果(效果: 技能效果): string {
  switch (效果.type) {
    case '施加状态':
      return `施加${效果.状态}${效果.强度 ? ` 强度${效果.强度}` : ''}${效果.层数 ? ` ×${效果.层数}` : ''}`;
    case '调整数值': {
      const 段: string[] = [];
      const 数 = 效果.数值;
      if (数.生命 !== undefined) 段.push(`生命${符号数(数.生命)}`);
      if (数.SP !== undefined) 段.push(`SP${符号数(数.SP)}`);
      if (数.攻击等级 !== undefined) 段.push(`攻击等级${符号数(数.攻击等级)}`);
      if (数.防御等级 !== undefined) 段.push(`防御等级${符号数(数.防御等级)}`);
      return 段.join(' ') || '数值调整';
    }
    case '震颤引爆':
      return '震颤引爆';
    case '获得护盾':
      return `获得护盾+${效果.数值}`;
    case '条件增伤':
      return `${效果.条件}时威力+${效果.数值}`;
  }
}

/** 将效果列表转为中文短句 */
export function 描述效果列表(效果列表: 技能效果[]): string {
  return 效果列表.map(描述效果).join('; ');
}

/** 简易条件判定: 支持 生命低于/高于 N%、SP/理智值低于/高于 N、满生命、混乱 等短语 */
export function 满足条件(单位: 战斗单位, 条件?: string): boolean {
  if (!条件) return true;
  const 生命比 = 单位.生命上限 > 0 ? 单位.生命值 / 单位.生命上限 : 0;
  let 匹配: RegExpMatchArray | null = null;
  if ((匹配 = 条件.match(/生命低于\s*(-?\d+)\s*%/))) return 生命比 < Number(匹配[1]) / 100;
  if ((匹配 = 条件.match(/生命高于\s*(-?\d+)\s*%/))) return 生命比 > Number(匹配[1]) / 100;
  if ((匹配 = 条件.match(/(?:SP|理智值?)低于\s*(-?\d+)/))) return 单位.理智值 < Number(匹配[1]);
  if ((匹配 = 条件.match(/(?:SP|理智值?)高于\s*(-?\d+)/))) return 单位.理智值 > Number(匹配[1]);
  if (/生命值?满/.test(条件)) return 单位.生命值 >= 单位.生命上限;
  if (/未混乱/.test(条件)) return !是否混乱(单位);
  if (/混乱/.test(条件)) return 是否混乱(单位);
  if (/生命值?未满/.test(条件)) return 单位.生命值 < 单位.生命上限;
  return true;
}

/** 命中后按 rupt/流血/烧伤/震颤/沉沦/充能 施加状态; 优先使用结构化 effects, 否则回退字符串 效果 */
export function 施加技能附带状态(攻击方: 战斗单位, 受击方: 战斗单位, 技能: 技能): void {
  if (技能.effects && 技能.effects.length > 0) {
    执行效果(攻击方, 受击方, 技能.effects);
    return;
  }
  const 效果 = 技能.效果;
  if (!效果) return;
  const 规则: Array<[string, string]> = [
    ['破裂', '破裂'],
    ['流血', '流血'],
    ['烧伤', '烧伤'],
    ['震颤', '震颤'],
    ['沉沦', '沉沦'],
  ];
  for (const [关键词, 状态名] of 规则) {
    if (效果.includes(关键词)) 增加状态(受击方, 状态名, 1, 1);
  }
  if (效果.includes('充能')) 增加状态(攻击方, '充能', 1, 1);
  if (效果.includes('震颤引爆') && 读取(受击方, '震颤') > 0) {
    const 强度 = 读取强度(受击方, '震颤');
    if (强度 > 0) 受击方.混乱阈值 = Math.max(1, 受击方.混乱阈值 - 强度);
    消耗层数(受击方, '震颤', 1);
  }
}

/** 罪孽名守卫, 供外部过滤 */
export function 是罪孽名(值: string): 值 is 罪孽名 {
  return (罪孽列表 as string[]).includes(值);
}
